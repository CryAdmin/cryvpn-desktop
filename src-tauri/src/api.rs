//! Разговор с кабинетом CryVPN.
//!
//! Почему запросы идут отсюда, а не из окна: сервер пускает только
//! `https://cryvps.com` и локальный адрес разработки. У окна приложения
//! источник другой, и браузерный запрос из него сервер отклонит. Из
//! нативной части таких ограничений нет вовсе — это не браузер.
//!
//! Куки держим сами: вход выдаёт refresh-куку, без неё продлить сессию
//! нельзя и человек будет вводить код с почты каждый запуск.

use std::sync::Arc;

use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

/// Адреса кабинета, по убыванию предпочтения. Первые два ведут на один и
/// тот же сервер. Запасной нужен потому, что имя `api.cryvps.com` находится не
/// через всякий DNS: под чужим VPN приложение получало «адрес не найден»
/// и не могло даже начать вход.
///
/// Третий стоит на другом сервере и нужен там, где провайдер не пускает к
/// первым двум: у части людей в России основной адрес не открывается
/// вовсе, пока не включён VPN, — а без входа его и не включить.
const БАЗЫ: [&str; 3] = [
    "https://api.cryvps.com/api/v2",
    "https://cryvps.com/api",
    "https://crysubik.com/api",
];

/// Какой адрес сработал в прошлый раз — с него и начинаем.
static РАБОЧАЯ: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

/// Шлём запрос на кабинет, при неудаче связи пробуем запасной адрес.
///
/// Запасной идёт в ход только когда до сервера не дозвонились вовсе или
/// ответил не он сам, а прокладка перед ним (502, 503). Ответ самого
/// кабинета, даже с ошибкой, окончателен: повторять его не нужно.
async fn послать(
    собрать: impl Fn(&str) -> reqwest::RequestBuilder,
) -> Result<reqwest::Response, reqwest::Error> {
    use std::sync::atomic::Ordering;
    let начало = РАБОЧАЯ.load(Ordering::Relaxed);
    let mut беда = None;
    let mut слабый = None;
    for шаг in 0..БАЗЫ.len() {
        let номер = (начало + шаг) % БАЗЫ.len();
        let старт = std::time::Instant::now();
        match собрать(БАЗЫ[номер]).send().await {
            // 502 и 503 — прокладка не дозвонилась до кабинета, запрос до него
            // не дошёл. 504 сюда не входит: там кабинет запрос получил и мог
            // выполнить, повтор отправил бы второе письмо с кодом.
            Ok(ответ) if matches!(ответ.status().as_u16(), 502 | 503) => слабый = Some(ответ),
            Ok(ответ) => {
                РАБОЧАЯ.store(номер, Ordering::Relaxed);
                return Ok(ответ);
            }
            // Только если не дозвонились вовсе. Когда запрос уже ушёл, а ответ
            // не вернулся, повторять нельзя: сервер мог его выполнить. Так
            // запрос кода уходил дважды — первое письмо отправлено, а на
            // повтор сервер отвечал «подождите», и человек получал
            // несколько писем, из которых годился только последний код.
            // Таймаут в первые секунды — это не дождались самой связи (на неё
            // отведено четыре), запрос ещё никуда не ушёл.
            Err(e) if e.is_connect() || (e.is_timeout() && старт.elapsed().as_secs() < 6) => {
                беда = Some(e)
            }
            Err(e) => return Err(e),
        }
    }
    // Если хоть до одного адреса не дозвонились, честнее сказать «нет
    // связи», чем показывать человеку 502 от запасного сервера.
    match (слабый, беда) {
        (_, Some(e)) => Err(e),
        (Some(ответ), None) => Ok(ответ),
        (None, None) => unreachable!("адресов кабинета не меньше одного"),
    }
}

/// Чем приложение представляется серверу. Видно в списке сессий кабинета,
/// поэтому пишем честно: человек должен отличать свой компьютер от браузера.
// Кем приложение называет себя серверу. По этой подписи кабинет и панель
// показывают устройство в списке — она должна совпадать с системой, иначе
// телефон выглядит там как компьютер.
#[cfg(target_os = "macos")]
const ПРЕДСТАВЛЕНИЕ: &str = concat!("CryVPN-macOS/", env!("CARGO_PKG_VERSION"));
#[cfg(target_os = "android")]
const ПРЕДСТАВЛЕНИЕ: &str = concat!("CryVPN-Android/", env!("CARGO_PKG_VERSION"));
#[cfg(target_os = "linux")]
const ПРЕДСТАВЛЕНИЕ: &str = concat!("CryVPN-Linux/", env!("CARGO_PKG_VERSION"));
#[cfg(not(any(target_os = "macos", target_os = "android", target_os = "linux")))]
const ПРЕДСТАВЛЕНИЕ: &str = concat!("CryVPN-Windows/", env!("CARGO_PKG_VERSION"));

/// Клиент живёт всё время работы приложения: в нём хранилище кук.
pub struct Кабинет {
    http: reqwest::Client,
    /// Токен доступа держим только в памяти. На диск не кладём: украденный
    /// файл не должен давать вход в чужой кабинет.
    pub токен: Arc<tokio::sync::Mutex<Option<String>>>,
    /// Конфигурации серверов из подписки. Тоже только в памяти: по ним
    /// открывается доступ к VPN, на диске им делать нечего.
    pub подписка: Arc<tokio::sync::Mutex<Vec<Value>>>,
    /// Очередь на продление входа и время последней удачи. Сервер при
    /// продлении выдаёт новую куку, а прежнюю гасит: два продления разом —
    /// и второе получило бы отказ, который мы прочли бы как «вход отозван».
    продление: Arc<tokio::sync::Mutex<Option<std::time::Instant>>>,
}

/// Всё, что Ремна сообщает вместе с подписκой: серверы, как часто
/// обновляться, объявление владельца и остаток трафика.
#[derive(Debug, Serialize, Deserialize, Default)]
pub struct Подписка {
    pub серверы: Vec<Сервер>,
    /// Часы между обновлениями. Значение берём у панели, а не выдумываем:
    /// владелец меняет его там и ожидает, что клиенты послушаются.
    pub интервал_часов: u32,
    pub объявление: String,
    pub объявление_ссылка: String,
    /// Сайт владельца из заголовка `profile-web-page-url`.
    pub сайт: String,
    pub потрачено: u64,
    pub всего: u64,
    /// Когда кончается подписка, секунды эпохи; 0 — панель не сказала.
    pub истекает: u64,
    /// Список не свежий, а сохранённый с прошлого раза: до панели сейчас
    /// не достучаться.
    #[serde(default)]
    pub из_памяти: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Сервер {
    pub номер: usize,
    pub имя: String,
    /// Заглушка панели: адрес `0.0.0.0`, порт 1. Показывать такое человеку
    /// как рабочий сервер нельзя — он будет жать «подключить» впустую.
    pub поддельный: bool,
}

/// Начало входа через Telegram: ссылка на бота и токен для опроса.
#[derive(Serialize)]
pub struct НачалоТелеграма {
    pub ok: bool,
    pub токен: String,
    pub адрес: String,
    pub сообщение: String,
}

/// Чем кончился очередной опрос: «ждём», «вошли» или «отказ».
#[derive(Serialize)]
pub struct ОпросТелеграма {
    pub состояние: String,
    pub сообщение: String,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct Ответ {
    pub ok: bool,
    /// Что показать человеку. Сообщения сервера уже написаны по-русски
    /// и для людей, поэтому передаём их как есть.
    pub сообщение: String,
}

impl Кабинет {
    pub fn новый() -> Result<Self, String> {
        let http = reqwest::Client::builder()
            .user_agent(ПРЕДСТАВЛЕНИЕ)
            // Системный прокси не используем никогда. Его прописывают
            // другие VPN-клиенты, и адрес этот — локальный порт, который
            // живёт, пока жив тот клиент. Библиотека читает настройку один
            // раз при запуске: стоило чужому клиенту убрать прокси или
            // сменить режим, как все наши запросы начинали падать с
            // «error sending request» до перезапуска приложения — при
            // живом интернете и рабочем сервере. Воспроизведено 12.11.2026.
            .no_proxy()
            // Соединения про запас не держим. Мы сами меняем маршруты,
            // поднимая и снимая туннель; соединение, открытое по старому
            // пути, после этого мертво, и запрос по нему висит до таймаута.
            .pool_max_idle_per_host(0)
            .cookie_store(true)
            // На установку связи — немного: если адрес недоступен, быстрее
            // перейти к запасному, чем держать человека двадцать секунд.
            .connect_timeout(std::time::Duration::from_secs(4))
            .timeout(std::time::Duration::from_secs(20))
            .build()
            .map_err(|e| format!("не удалось создать http-клиент: {e}"))?;
        Ok(Self {
            http,
            токен: Arc::new(tokio::sync::Mutex::new(None)),
            подписка: Arc::new(tokio::sync::Mutex::new(Vec::new())),
            продление: Arc::new(tokio::sync::Mutex::new(None)),
        })
    }

    async fn почтой(&self, путь: &str, тело: Value) -> Result<(u16, Value), String> {
        let ответ = послать(|база| self.http.post(format!("{база}{путь}")).json(&тело))
            .await
            .map_err(|e| {
                let вовремя = !e.is_timeout();
                let причина = расшифровать_ошибку(e);
                записать_ошибку(путь, &причина);
                if вовремя {
                    format!("Нет связи с сервером: {причина}")
                } else {
                    "Сервер не ответил. Проверьте интернет".to_string()
                }
            })?;

        let код = ответ.status().as_u16();
        // Вход и продление возвращают refresh-куку. Запоминаем её сразу здесь:
        // иначе при следующем запуске придётся снова просить код на почту,
        // а число писем с кодом на один адрес ограничено.
        запомнить_куку(ответ.headers());
        let текст = ответ.text().await.unwrap_or_default();

        // Если перед API однажды встанет проверка антиддоса, сюда придёт html.
        // Тогда лучше честно сказать, чем молча показать «неверный код».
        if текст.trim_start().starts_with('<') {
            return Err("Сервер вернул страницу проверки вместо ответа".into());
        }

        let данные: Value = serde_json::from_str(&текст).unwrap_or(json!({}));
        Ok((код, данные))
    }

    /// Шаг первый: просим выслать код на почту.
    pub async fn выслать_код(&self, почта: &str) -> Ответ {
        match self.почтой("/auth/web/send_code", json!({ "email": почта })).await {
            Err(беда) => Ответ { ok: false, сообщение: беда },
            Ok((код, данные)) => match код {
                200 => Ответ { ok: true, сообщение: "Код отправлен на почту".into() },
                429 => Ответ {
                    ok: false,
                    сообщение: "Подождите перед повторным запросом кода".into(),
                },
                _ => Ответ {
                    ok: false,
                    сообщение: сообщение_сервера(&данные)
                        .unwrap_or_else(|| "Не удалось отправить код".into()),
                },
            },
        }
    }

    /// Шаг второй: меняем код из письма на токен доступа.
    pub async fn проверить_код(&self, почта: &str, код_из_письма: &str) -> Ответ {
        match self
            .почтой(
                "/auth/web/verify_code",
                json!({ "email": почта, "code": код_из_письма }),
            )
            .await
        {
            Err(беда) => Ответ { ok: false, сообщение: беда },
            Ok((код, данные)) => {
                if код == 200 {
                    if let Some(токен) = данные.get("access_token").and_then(|t| t.as_str()) {
                        *self.токен.lock().await = Some(токен.to_string());
                        return Ответ { ok: true, сообщение: "Вход выполнен".into() };
                    }
                    return Ответ {
                        ok: false,
                        сообщение: "Сервер не вернул токен входа".into(),
                    };
                }
                // «Неверный код» говорим только когда это сказал сервер.
                // На всё остальное — честно называем, что пошло не так.
                Ответ {
                    ok: false,
                    сообщение: сообщение_сервера(&данные).unwrap_or_else(|| match код {
                        400 => "Неверный код".into(),
                        429 => "Слишком много попыток. Подождите минуту".into(),
                        прочее => format!("Сервер ответил {прочее}. Попробуйте ещё раз"),
                    }),
                }
            }
        }
    }

    /// Вход через Telegram, шаг первый: берём у кабинета одноразовую
    /// ссылку на бота. Человек открывает её и подтверждает вход кнопкой.
    pub async fn телеграм_начать(&self) -> НачалоТелеграма {
        let отказ = |сообщение: String| НачалоТелеграма {
            ok: false,
            токен: String::new(),
            адрес: String::new(),
            сообщение,
        };
        match self.почтой("/auth/app/tg/start", json!({})).await {
            Err(беда) => отказ(беда),
            Ok((200, данные)) => {
                let токен = данные.get("token").and_then(|т| т.as_str()).unwrap_or("");
                let адрес = данные.get("url").and_then(|а| а.as_str()).unwrap_or("");
                // Открываем только настоящий Telegram: что бы ни прислал
                // сервер, в другое место человека отсюда не уведём.
                if токен.is_empty() || !адрес.starts_with("https://t.me/") {
                    return отказ("Сервер прислал неверную ссылку для входа".into());
                }
                НачалоТелеграма {
                    ok: true,
                    токен: токен.to_string(),
                    адрес: адрес.to_string(),
                    сообщение: String::new(),
                }
            }
            Ok((429, _)) => отказ("Слишком много попыток входа. Подождите минуту".into()),
            Ok((_, данные)) => отказ(
                сообщение_сервера(&данные)
                    .unwrap_or_else(|| "Не удалось начать вход через Telegram".into()),
            ),
        }
    }

    /// Шаг второй: спрашиваем, нажал ли человек «Войти» в боте.
    pub async fn телеграм_опрос(&self, токен: &str) -> ОпросТелеграма {
        let итог = |состояние: &str, сообщение: String| ОпросТелеграма {
            состояние: состояние.to_string(),
            сообщение,
        };
        match self.почтой("/auth/app/tg/poll", json!({ "token": токен })).await {
            // Сеть моргнула — это не отказ, спросим ещё раз.
            Err(_) | Ok((202, _)) => итог("ждём", String::new()),
            Ok((200, данные)) => match данные.get("access_token").and_then(|т| т.as_str()) {
                Some(вход) => {
                    *self.токен.lock().await = Some(вход.to_string());
                    итог("вошли", String::new())
                }
                None => итог("отказ", "Сервер не вернул токен входа".into()),
            },
            Ok((429, _)) => итог("отказ", "Вход ждал слишком долго. Начните заново".into()),
            Ok((_, данные)) => итог(
                "отказ",
                сообщение_сервера(&данные).unwrap_or_else(|| "Вход не удался".into()),
            ),
        }
    }

    /// Всё о человеке: подписка, серверы, устройства, срок.
    pub async fn профиль(&self) -> Result<Value, String> {
        // Токен доступа живёт недолго, сессия — три месяца. Если токен
        // истёк, продлеваем его сами и повторяем запрос. Раньше приложение
        // в этом месте говорило «войдите заново», хотя вход был жив.
        for попытка in 0..2 {
            // Токена в памяти может не быть, хотя вход жив: прошлое продление
            // сорвалось из-за сети. Пробуем продлить ещё раз, прежде чем
            // говорить человеку, что он не вошёл.
            let в_памяти = self.токен.lock().await.clone();
            let токен = match в_памяти {
                Some(токен) => токен,
                None => {
                    if !self.восстановить().await {
                        return Err(if прочитать_сессию().is_some() {
                            "Нет связи с сервером. Попробуйте ещё раз".to_string()
                        } else {
                            "Вход не выполнен".to_string()
                        });
                    }
                    self.токен.lock().await.clone().ok_or_else(|| "Вход не выполнен".to_string())?
                }
            };

            let ответ = послать(|база| self.http.post(format!("{база}/get/me")).bearer_auth(&токен))
                .await
                .map_err(|e| {
                    let причина = расшифровать_ошибку(e);
                    записать_ошибку("профиль", &причина);
                    format!("Нет связи с сервером: {причина}")
                })?;

            if ответ.status() == 401 {
                if попытка == 0 && self.восстановить().await {
                    continue;
                }
                *self.токен.lock().await = None;
                // Сессию стирает только настоящий отказ сервера. Если она на
                // месте, значит продление сорвалось из-за связи — так и скажем,
                // и следующая попытка продлит вход сама.
                return Err(if прочитать_сессию().is_some() {
                    "Нет связи с сервером. Попробуйте ещё раз".to_string()
                } else {
                    "Сессия истекла, войдите заново".to_string()
                });
            }
            if !ответ.status().is_success() {
                return Err(format!("Сервер ответил {}", ответ.status().as_u16()));
            }

            let профиль = ответ
                .json::<Value>()
                .await
                .map_err(|e| format!("Не разобрать ответ сервера: {e}"))?;
            // Запоминаем на случай, когда до кабинета не достучаться: без
            // этого приложение показывало экран входа при живой сессии.
            запомнить(ПАМЯТЬ_ПРОФИЛЯ, профиль.to_string());
            return Ok(профиль);
        }
        Err("Сессия истекла, войдите заново".into())
    }

    /// Серверы берём из подписки Ремны, а не из профиля: поле `connections`
    /// у кабинета пустое, настоящие узлы живут только в подписке.
    ///
    /// Без заголовка `x-hwid` панель отдаёт заглушку с одним выдуманным
    /// сервером `0.0.0.0:1` и надписью «Переустанови приложение!» — проверено
    /// на живой подписке 11.11.2026. Поэтому представляемся устройством.
    pub async fn серверы(&self, ссылка: &str) -> Result<Подписка, String> {
        let (ос, версия, модель) = crate::device::описание();

        // Сеть в момент переключения VPN моргает на секунду-другую. Один
        // сорвавшийся запрос не должен оставлять человека с пустым списком
        // и красной надписью: пробуем до трёх раз и жалуемся только потом.
        //
        // У подписки два адреса на разных серверах. Там, где провайдер не
        // пускает к основному, второй остаётся доступен — пробуем оба.
        let адреса = адреса_подписки(ссылка);
        // Отказ панели (не тот статус, предел устройств) — его разберём ниже.
        let mut отказ: Option<reqwest::Response> = None;
        let mut готово: Option<(reqwest::header::HeaderMap, Value)> = None;
        let mut беда = String::new();
        'попытки: for попытка in 0..3 {
            if попытка > 0 {
                tokio::time::sleep(std::time::Duration::from_millis(800)).await;
            }
            for адрес in &адреса {
                let о = match self
                    .http
                    .get(format!("{адрес}/json"))
                    .header("x-hwid", crate::device::номер())
                    .header("x-device-os", &ос)
                    .header("x-ver-os", &версия)
                    .header("x-device-model", &модель)
                    .send()
                    .await
                {
                    Ok(о) => о,
                    Err(e) => {
                        беда = расшифровать_ошибку(e);
                        записать_ошибку("подписка", &беда);
                        continue;
                    }
                };
                // Прокладка перед панелью не достучалась до неё —
                // спросим через другой адрес, а этот ответ придержим.
                if matches!(о.status().as_u16(), 502..=504) {
                    отказ = Some(о);
                    continue;
                }
                if !о.status().is_success()
                    || о.headers().get("x-hwid-max-devices-reached").is_some()
                {
                    отказ = Some(о);
                    break 'попытки;
                }
                // Заголовки пришли — это ещё не весь ответ. На слабой или
                // придушенной связи список серверов обрывается на середине,
                // а иногда вместо него приходит чужая страница. Раньше это
                // сразу кончалось ошибкой на экране; теперь это такая же
                // неудачная попытка, как и несостоявшееся соединение.
                let заголовки = о.headers().clone();
                let тело = match о.bytes().await {
                    Ok(т) => т,
                    Err(e) => {
                        беда = format!("ответ оборвался: {}", расшифровать_ошибку(e));
                        записать_ошибку("подписка", &беда);
                        continue;
                    }
                };
                match serde_json::from_slice::<Value>(&тело) {
                    Ok(д) if д.is_array() => {
                        готово = Some((заголовки, д));
                        break 'попытки;
                    }
                    // Само содержимое в журнал не кладём: в нём могут быть
                    // ключи серверов.
                    _ => {
                        беда = format!("вместо списка серверов пришло другое ({} байт)", тело.len());
                        записать_ошибку("подписка", &беда);
                    }
                }
            }
        }
        let (заголовки, данные) = match (готово, отказ) {
            (Some(г), _) => г,
            (None, Some(ответ)) => {
                // Прокладка не достучалась до панели — это беда связи, а
                // не отказ: показываем то, что помним.
                if matches!(ответ.status().as_u16(), 502..=504) {
                    if let Some(старая) = self.подписка_из_памяти(ссылка).await {
                        return Ok(старая);
                    }
                }
                if ответ.headers().get("x-hwid-max-devices-reached").is_some() {
                    return Err("Достигнут предел устройств. Отключите лишнее в кабинете".into());
                }
                if ответ.status() == 404 {
                    return Err("Подписка не найдена или устройство не принято панелью".into());
                }
                return Err(format!("Панель ответила {}", ответ.status().as_u16()));
            }
            (None, None) => {
                // Сеть, в которой открываются только разрешённые сайты, до
                // панели не пускает, а до самих серверов VPN может пускать.
                // Тогда человеку нужен именно прошлый список: с ним можно
                // подключиться, не дожидаясь панели.
                if let Some(старая) = self.подписка_из_памяти(ссылка).await {
                    return Ok(старая);
                }
                // Подробности уже в журнале ошибок; человеку от «error
                // sending request» толку нет — говорим, что это значит.
                let _ = беда;
                return Err("Похоже, работают белые списки или нет интернета — подписку не обновить".into());
            }
        };

        let список = данные.as_array().cloned().unwrap_or_default();
        let серверы: Vec<Сервер> = список
            .iter()
            .enumerate()
            .map(|(номер, конфиг)| Сервер {
                номер,
                имя: конфиг
                    .get("remarks")
                    .and_then(|v| v.as_str())
                    .unwrap_or("Без названия")
                    .to_string(),
                поддельный: поддельный(конфиг),
            })
            .collect();

        if серверы.iter().all(|с| с.поддельный) {
            return Err(
                "Панель не приняла это устройство: настоящих серверов в подписке нет".into(),
            );
        }

        // Конфигурации держим у себя: по ним потом будет подниматься туннель.
        // Подменяем их только годным списком. Раньше замена шла до проверки,
        // и неудачное обновление молча клало сюда заглушки: человек выбирал
        // сервер из прежнего списка на экране, а подключался к пустышке.
        *self.подписка.lock().await = список;

        let (потрачено, всего, истекает) = разобрать_трафик(&заголовки);
        let итог = Подписка {
            серверы,
            интервал_часов: заголовок(&заголовки, "profile-update-interval")
                .and_then(|з| з.parse().ok())
                .filter(|ч: &u32| *ч > 0)
                .unwrap_or(1),
            объявление: заголовок(&заголовки, "announce")
                .map(|з| раскодировать(&з))
                .unwrap_or_default(),
            объявление_ссылка: заголовок(&заголовки, "announce-url").unwrap_or_default(),
            сайт: заголовок(&заголовки, "profile-web-page-url").unwrap_or_default(),
            потрачено,
            всего,
            истекает,
            из_памяти: false,
        };
        // Сами конфигурации открывают доступ к VPN, поэтому на диск они
        // ложатся только зашифрованными — тем же способом, что и сессия.
        let запись = json!({
            "ссылка": ссылка,
            "конфиги": *self.подписка.lock().await,
            "сведения": итог,
        });
        запомнить(ПАМЯТЬ_ПОДПИСКИ, запись.to_string());
        Ok(итог)
    }

    /// Замер задержки до каждого сервера: время установки TCP-соединения.
    ///
    /// Это не «пинг» в строгом смысле, а то, что человеку и нужно знать:
    /// сколько идёт до сервера по тому же пути, которым пойдёт туннель.
    /// У конфигураций с несколькими узлами («Авто выбор») берём лучший.
    /// Не дозвонились — отдаём пусто, а не выдуманное число.
    ///
    /// `мимо` — адрес компьютера в обычной сети. Когда туннель поднят,
    /// замер привязывается к нему и идёт мимо туннеля, иначе мерили бы
    /// сами себя и получали ноль.
    pub async fn пинг(&self, мимо: Option<std::net::Ipv4Addr>) -> Vec<Option<u32>> {
        let подписка = self.подписка.lock().await.clone();
        let задачи = подписка.into_iter().map(|конфиг| async move {
            let адреса = адреса_узлов(&конфиг);
            let замеры = адреса.into_iter().map(|(хост, порт, имя)| async move {
                замер_узла(&хост, порт, имя.as_deref(), мимо).await
            });
            let mut лучший: Option<u32> = None;
            for итог in futures_вместе(замеры).await {
                if let Some(мс) = итог {
                    лучший = Some(лучший.map_or(мс, |б| б.min(мс)));
                }
            }
            лучший
        });
        futures_вместе(задачи).await
    }

    /// Прошлый удачный список серверов — для случая, когда до панели не
    /// достучаться. Берём его, только если он от той же подписки.
    pub async fn подписка_из_памяти(&self, ссылка: &str) -> Option<Подписка> {
        let запись: Value =
            serde_json::from_str(&crate::secrets::прочитать(ПАМЯТЬ_ПОДПИСКИ)?).ok()?;
        if запись.get("ссылка")?.as_str()? != ссылка {
            return None;
        }
        let конфиги = запись.get("конфиги")?.as_array()?.clone();
        let mut сведения: Подписка =
            serde_json::from_value(запись.get("сведения")?.clone()).ok()?;
        if конфиги.is_empty() || сведения.серверы.len() != конфиги.len() {
            return None;
        }
        сведения.из_памяти = true;
        *self.подписка.lock().await = конфиги;
        Some(сведения)
    }

    /// Возвращаемся в уже начатую сессию, без письма с кодом.
    ///
    /// Так же работает сайт: у браузера лежит refresh-кука, и кабинет при
    /// открытии просто продлевает вход. Без этого приложение просило бы код
    /// при каждом запуске, а число писем с кодом на адрес ограничено.
    pub async fn восстановить(&self) -> bool {
        self.вернуться().await == Возврат::Вошли
    }

    /// То же, но с ответом на главный вопрос: нас не пустили или до
    /// сервера просто не достучаться. Во втором случае вход жив, и
    /// показывать человеку экран входа нельзя.
    pub async fn вернуться(&self) -> Возврат {
        // По одному: кто пришёл вторым, ждёт первого и пользуется его удачей.
        let mut продление = self.продление.lock().await;
        if продление.is_some_and(|когда| когда.elapsed().as_secs() < 10)
            && self.токен.lock().await.is_some()
        {
            return Возврат::Вошли;
        }
        let Some(кука) = прочитать_сессию() else {
            return Возврат::Нет;
        };

        let ответ = послать(|база| {
            self.http
                .post(format!("{база}/auth/refresh"))
                .header("Cookie", format!("refresh_token={кука}"))
        })
        .await;

        let Ok(ответ) = ответ else { return Возврат::НетСвязи };

        if ответ.status() != 200 {
            // 401 здесь — обычное дело: сессия истекла или человек вышел.
            // Файл убираем, чтобы не стучаться с мёртвой кукой каждый запуск.
            if ответ.status() == 401 {
                забыть_сессию();
                // Вход отозван — сохранённым серверам тоже конец: иначе
                // отключённый аккаунт продолжал бы видеть список.
                забыть_память();
                return Возврат::Нет;
            }
            // Сервер или прокладка перед ним сломались — вход тут ни при чём.
            return if ответ.status().is_server_error() {
                Возврат::НетСвязи
            } else {
                Возврат::Нет
            };
        }

        запомнить_куку(ответ.headers());

        let Ok(данные) = ответ.json::<Value>().await else {
            return Возврат::НетСвязи;
        };
        match данные.get("access_token").and_then(|t| t.as_str()) {
            Some(токен) => {
                *self.токен.lock().await = Some(токен.to_string());
                *продление = Some(std::time::Instant::now());
                Возврат::Вошли
            }
            None => Возврат::Нет,
        }
    }

    /// Выход. Токен забываем в любом случае — даже если сервер не ответил:
    /// человек нажал «выйти» и должен увидеть экран входа, а не ошибку.
    pub async fn выйти(&self) -> Ответ {
        let токен = self.токен.lock().await.clone();
        if let Some(токен) = токен {
            let _ = послать(|база| self.http.post(format!("{база}/auth/logout")).bearer_auth(&токен))
                .await;
        }
        *self.токен.lock().await = None;
        self.подписка.lock().await.clear();
        забыть_сессию();
        забыть_память();
        Ответ { ok: true, сообщение: "Вы вышли".into() }
    }
}

/// Чем кончилась попытка вернуться в прошлый вход.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Возврат {
    Вошли,
    /// Входа нет: его не было, он истёк или сервер его отверг.
    Нет,
    /// Вход на месте, но до сервера не достучаться.
    НетСвязи,
}

// Что помним с прошлого удачного раза, чтобы приложение работало там, где
// до кабинета не достучаться. Лежит зашифрованным, как и сессия.
const ПАМЯТЬ_ПРОФИЛЯ: &str = "profile";
const ПАМЯТЬ_ПОДПИСКИ: &str = "subscription";

/// Шифрование на Windows — это запуск отдельной программы, на полсекунды.
/// Ответ человеку из-за этого ждать не должен: пишем в стороне.
fn запомнить(имя: &'static str, текст: String) {
    // Проверки ходят к выдуманным серверам — в настоящую память их ответам
    // дороги нет.
    if cfg!(test) {
        return;
    }
    tokio::task::spawn_blocking(move || {
        crate::secrets::сохранить(имя, &текст);
    });
}

/// Профиль с прошлого удачного запроса.
pub fn профиль_из_памяти() -> Option<Value> {
    // Нет сохранённого входа — нет и профиля: помним только для того, кто
    // вошёл и чей вход сервер не отвергал.
    прочитать_сессию()?;
    serde_json::from_str(&crate::secrets::прочитать(ПАМЯТЬ_ПРОФИЛЯ)?).ok()
}

/// Выход и смена аккаунта: чужого в памяти оставаться не должно.
pub fn забыть_память() {
    crate::secrets::забыть(ПАМЯТЬ_ПРОФИЛЯ);
    crate::secrets::забыть(ПАМЯТЬ_ПОДПИСКИ);
    // Android: зашифрованная конфигурация прошлого подключения, по которой
    // плитка в шторке включает VPN без приложения. Вышел — плитке больше
    // включать нечем.
    if let Some(папка) = crate::paths::папка_данных() {
        let _ = std::fs::remove_file(папка.join("last.dat"));
    }
}

// Сессия продления — то же самое, что браузер держит в куке: по ней можно
// продлить вход, пока её не отозвали. Хранится в защищённом хранилище.
const СЕССИЯ: &str = "session";

fn прочитать_сессию() -> Option<String> {
    crate::secrets::прочитать(СЕССИЯ)
}

fn сохранить_сессию(значение: &str) {
    crate::secrets::сохранить(СЕССИЯ, значение);
}

fn забыть_сессию() {
    crate::secrets::забыть(СЕССИЯ);
}

/// Вытаскиваем refresh-куку из ответа и запоминаем её.
/// Сервер её вращает: после каждого продления приходит новая, и если
/// сохранить старую, следующий запуск получит отказ.
fn запомнить_куку(заголовки: &reqwest::header::HeaderMap) {
    for значение in заголовки.get_all("set-cookie") {
        if let Ok(строка) = значение.to_str() {
            if let Some(хвост) = строка.strip_prefix("refresh_token=") {
                let токен = хвост.split(';').next().unwrap_or("").trim();
                if !токен.is_empty() {
                    сохранить_сессию(токен);
                }
            }
        }
    }
}

fn заголовок(заголовки: &reqwest::header::HeaderMap, имя: &str) -> Option<String> {
    заголовки
        .get(имя)
        .and_then(|з| з.to_str().ok())
        .map(|з| з.trim().to_string())
        .filter(|з| !з.is_empty())
}

/// Объявление приходит либо текстом, либо с пометкой «base64:».
fn раскодировать(значение: &str) -> String {
    let Some(тело) = значение.strip_prefix("base64:") else {
        return значение.to_string();
    };
    match base64_в_байты(тело) {
        Some(байты) => String::from_utf8_lossy(&байты).to_string(),
        None => String::new(),
    }
}

/// Маленький разбор base64: тянуть ради одного заголовка целую
/// библиотеку незачем.
pub(crate) fn base64_в_байты(вход: &str) -> Option<Vec<u8>> {
    const АЗБУКА: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut биты: u32 = 0;
    let mut сколько = 0;
    let mut итог = Vec::new();
    for знак in вход.bytes() {
        if знак == b'=' || знак == b'\n' || знак == b'\r' {
            continue;
        }
        let позиция = АЗБУКА.iter().position(|&э| э == знак)? as u32;
        биты = (биты << 6) | позиция;
        сколько += 6;
        if сколько >= 8 {
            сколько -= 8;
            итог.push((биты >> сколько) as u8);
        }
    }
    Some(итог)
}

/// `subscription-userinfo: upload=0; download=123; total=456; expire=789`
fn разобрать_трафик(заголовки: &reqwest::header::HeaderMap) -> (u64, u64, u64) {
    let Some(строка) = заголовок(заголовки, "subscription-userinfo") else {
        return (0, 0, 0);
    };
    let mut истекает = 0u64;
    let mut вверх = 0u64;
    let mut вниз = 0u64;
    let mut всего = 0u64;
    for кусок in строка.split(';') {
        let mut части = кусок.trim().splitn(2, '=');
        let (Some(ключ), Some(значение)) = (части.next(), части.next()) else {
            continue;
        };
        let число = значение.trim().parse::<u64>().unwrap_or(0);
        match ключ.trim() {
            "upload" => вверх = число,
            "download" => вниз = число,
            "total" => всего = число,
            "expire" => истекает = число,
            _ => {}
        }
    }
    (вверх + вниз, всего, истекает)
}

/// Адрес подписки и его двойник на втором сервере.
///
/// Оба домена — наши и оба есть в списке разрешённых для ссылок
/// (`link.rs`); путь у них одинаковый. Чужой адрес сюда попасть не может:
/// двойник строится только для этих двух доменов.
fn адреса_подписки(ссылка: &str) -> Vec<String> {
    const ПАРА: [&str; 2] = ["https://sub.cryvps.com/", "https://crysubik.com/"];
    let ссылка = ссылка.trim_end_matches('/').to_string();
    let mut адреса = vec![ссылка.clone()];
    for (свой, другой) in [(ПАРА[0], ПАРА[1]), (ПАРА[1], ПАРА[0])] {
        if let Some(хвост) = ссылка.strip_prefix(свой) {
            адреса.push(format!("{другой}{хвост}"));
        }
    }
    адреса
}

/// Один узел: сначала узнаём адрес, потом трижды стучимся и берём лучшее.
///
/// Почему так. Первый замер раньше включал поиск имени в DNS и «прогрев»
/// маршрута, поэтому цифры прыгали: раз 40 мс, раз 180. Теперь имя
/// разрешается отдельно и в счёт не идёт, а из трёх попыток берётся
/// наименьшая — это и есть настоящая задержка до сервера, остальное шум.
async fn замер_узла(
    хост: &str,
    порт: u16,
    имя_tls: Option<&str>,
    мимо: Option<std::net::Ipv4Addr>,
) -> Option<u32> {
    let предел = std::time::Duration::from_secs(3);

    let адреса: Vec<std::net::SocketAddr> =
        tokio::time::timeout(предел, tokio::net::lookup_host((хост, порт)))
            .await
            .ok()?
            .ok()?
            .collect();
    // Привязаться к обычной сети можем только для IPv4.
    let адрес = match мимо {
        Some(_) => *адреса.iter().find(|а| а.is_ipv4())?,
        None => *адреса.first()?,
    };

    let mut лучший: Option<u32> = None;
    let mut запасной: Option<u32> = None;
    for _ in 0..2 {
        let начало = std::time::Instant::now();
        if let Ok(Ok(mut связь)) = tokio::time::timeout(предел, соединиться(адрес, мимо)).await {
            let на_связь = начало.elapsed().as_millis() as u32;
            запасной = Some(запасной.map_or(на_связь, |б| б.min(на_связь)));
            if let Some(имя) = имя_tls {
                if let Some(мс) = ответ_сервера(&mut связь, имя, предел).await {
                    лучший = Some(лучший.map_or(мс, |б| б.min(мс)));
                }
            }
        }
        tokio::time::sleep(std::time::Duration::from_millis(60)).await;
    }
    // Сервер без TLS или молчит на приветствие — остаётся время на связь.
    лучший.or(запасной)
}

/// Сколько сервер думает над ответом: шлём начало TLS-рукопожатия и ждём
/// первый байт.
///
/// Зачем так. Время установки соединения — плохой градусник: в мобильных
/// сетях и под чужим VPN соединение принимает узел по дороге, рядом с
/// телефоном, и замер показывал 10 мс хоть до Канады. Ответ на приветствие
/// может дать только сам сервер, поэтому здесь задержка настоящая.
/// Ничего секретного не уходит: приветствие — обычное начало TLS, после
/// первого байта соединение закрываем.
async fn ответ_сервера(
    связь: &mut tokio::net::TcpStream,
    имя: &str,
    предел: std::time::Duration,
) -> Option<u32> {
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    let приветствие = приветствие_tls(имя);
    let начало = std::time::Instant::now();
    tokio::time::timeout(предел, связь.write_all(&приветствие)).await.ok()?.ok()?;
    let mut байт = [0u8; 1];
    let прочитано = tokio::time::timeout(предел, связь.read(&mut байт)).await.ok()?.ok()?;
    (прочитано > 0).then(|| начало.elapsed().as_millis() as u32)
}

/// Собираем TLS ClientHello руками: ради одного пакета тянуть библиотеку
/// незачем. Вид у него как у обычного браузера — TLS 1.3 и 1.2, имя сервера,
/// ключ x25519. Случайные поля заполняем чем придётся: до настоящего обмена
/// ключами дело не дойдёт.
fn приветствие_tls(имя: &str) -> Vec<u8> {
    fn поле16(тело: &[u8]) -> Vec<u8> {
        let mut в = (тело.len() as u16).to_be_bytes().to_vec();
        в.extend_from_slice(тело);
        в
    }
    fn расширение(вид: u16, тело: &[u8]) -> Vec<u8> {
        let mut в = вид.to_be_bytes().to_vec();
        в.extend(поле16(тело));
        в
    }
    let шум = |сколько: usize| -> Vec<u8> {
        use std::hash::{BuildHasher, Hasher};
        let mut байты = Vec::with_capacity(сколько);
        while байты.len() < сколько {
            let mut х = std::collections::hash_map::RandomState::new().build_hasher();
            х.write_usize(байты.len());
            байты.extend_from_slice(&х.finish().to_be_bytes());
        }
        байты.truncate(сколько);
        байты
    };

    let mut расширения = Vec::new();
    // имя сервера
    let mut запись = vec![0u8];
    запись.extend(поле16(имя.as_bytes()));
    расширения.extend(расширение(0x0000, &поле16(&запись)));
    // кривые: x25519, secp256r1
    расширения.extend(расширение(0x000a, &поле16(&[0x00, 0x1d, 0x00, 0x17])));
    // подписи
    расширения.extend(расширение(
        0x000d,
        &поле16(&[0x04, 0x03, 0x08, 0x04, 0x04, 0x01, 0x05, 0x03, 0x08, 0x05, 0x05, 0x01, 0x08, 0x06, 0x06, 0x01]),
    ));
    // версии: TLS 1.3, TLS 1.2
    расширения.extend(расширение(0x002b, &[0x04, 0x03, 0x04, 0x03, 0x03]));
    // обмен ключами: x25519, 32 байта
    let mut ключ = vec![0x00, 0x1d];
    ключ.extend(поле16(&шум(32)));
    расширения.extend(расширение(0x0033, &поле16(&ключ)));

    let mut тело = vec![0x03, 0x03];
    тело.extend(шум(32));
    тело.push(32);
    тело.extend(шум(32));
    тело.extend(поле16(&[0x13, 0x01, 0x13, 0x02, 0x13, 0x03, 0xc0, 0x2b, 0xc0, 0x2f, 0xc0, 0x2c, 0xc0, 0x30]));
    тело.extend([0x01, 0x00]);
    тело.extend(поле16(&расширения));

    let mut рукопожатие = vec![0x01, 0x00];
    рукопожатие.extend(поле16(&тело));
    let mut пакет = vec![0x16, 0x03, 0x01];
    пакет.extend(поле16(&рукопожатие));
    пакет
}

/// Соединение с узлом; при заданном `мимо` — с обычного адреса компьютера,
/// то есть в обход туннеля.
async fn соединиться(
    адрес: std::net::SocketAddr,
    мимо: Option<std::net::Ipv4Addr>,
) -> std::io::Result<tokio::net::TcpStream> {
    match мимо {
        Some(свой) => {
            let гнездо = tokio::net::TcpSocket::new_v4()?;
            гнездо.bind(std::net::SocketAddr::from((свой, 0)))?;
            гнездо.connect(адрес).await
        }
        None => tokio::net::TcpStream::connect(адрес).await,
    }
}

/// Запускаем несколько замеров одновременно и ждём всех.
/// Ради этого не тянем отдельную библиотеку: хватает задач tokio.
async fn futures_вместе<Ф, Т>(набор: impl IntoIterator<Item = Ф>) -> Vec<Т>
where
    Ф: std::future::Future<Output = Т> + Send + 'static,
    Т: Send + 'static,
{
    let ручки: Vec<_> = набор.into_iter().map(tokio::spawn).collect();
    let mut итоги = Vec::with_capacity(ручки.len());
    for ручка in ручки {
        if let Ok(итог) = ручка.await {
            итоги.push(итог);
        }
    }
    итоги
}

/// Куда на самом деле стучится конфигурация: адреса и порты узлов.
fn адреса_узлов(конфиг: &Value) -> Vec<(String, u16, Option<String>)> {
    let mut найдено = Vec::new();
    for узел in конфиг.get("outbounds").and_then(|о| о.as_array()).into_iter().flatten() {
        // Имя, которым узел представляется в TLS: по нему шлём приветствие
        // при замере. Узел без шифрования остаётся без имени.
        let поток = узел.get("streamSettings");
        let защита = поток.and_then(|п| п.get("security")).and_then(|з| з.as_str()).unwrap_or("");
        let имя = ["realitySettings", "tlsSettings"]
            .iter()
            .filter_map(|раздел| поток?.get(раздел)?.get("serverName")?.as_str())
            .find(|и| !и.is_empty())
            .map(str::to_string);

        let настройки = узел.get("settings");
        for ключ in ["vnext", "servers"] {
            for запись in настройки
                .and_then(|н| н.get(ключ))
                .and_then(|в| в.as_array())
                .into_iter()
                .flatten()
            {
                let хост = запись.get("address").and_then(|а| а.as_str()).unwrap_or("");
                let порт = запись.get("port").and_then(|п| п.as_u64()).unwrap_or(0) as u16;
                if !хост.is_empty() && хост != "0.0.0.0" && порт > 0 {
                    let имя_tls = match защита {
                        "tls" | "reality" => имя.clone().or_else(|| Some(хост.to_string())),
                        _ => None,
                    };
                    найдено.push((хост.to_string(), порт, имя_tls));
                }
            }
        }
    }
    найдено.sort();
    найдено.dedup();
    // У «Авто выбора» узлов десятки: всех не обзваниваем, хватит первых.
    найдено.truncate(8);
    найдено
}

/// Сетевая ошибка целиком: что случилось и почему, по всей цепочке причин.
///
/// Раньше в окно попадала только верхняя фраза «error sending request», и
/// по ней нельзя было отличить обрыв связи от отказа DNS или ошибки
/// шифрования. Дважды из-за этого причину приходилось искать вслепую.
///
/// Адрес из текста убираем: в адресе подписки стоит её код, а эта строка
/// попадает в окно и в файл на диске.
fn расшифровать_ошибку(ошибка: reqwest::Error) -> String {
    use std::error::Error;
    let ошибка = ошибка.without_url();
    let mut текст = ошибка.to_string();
    let mut причина = ошибка.source();
    while let Some(п) = причина {
        текст.push_str(" ← ");
        текст.push_str(&п.to_string());
        причина = п.source();
    }
    текст
}

/// Последние ошибки связи пишем в файл: человек видит сообщение секунду,
/// а разбираться приходится потом. Секретов в записи нет.
fn записать_ошибку(где: &str, что: &str) {
    let Some(папка) = crate::paths::папка_данных() else { return };
    let путь = папка.join("errors.log");
    let прежнее = std::fs::read_to_string(&путь).unwrap_or_default();
    // Держим только хвост: журнал не должен расти без конца.
    let хвост: Vec<&str> = прежнее.lines().rev().take(60).collect();
    let mut итог: String = хвост.into_iter().rev().collect::<Vec<_>>().join("\n");
    if !итог.is_empty() {
        итог.push('\n');
    }
    let когда = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|д| д.as_secs())
        .unwrap_or(0);
    итог.push_str(&format!("{когда} {где}: {что}\n"));
    let _ = std::fs::write(путь, итог);
}

/// Узнаём заглушку панели: она всегда указывает на `0.0.0.0`.
fn поддельный(конфиг: &Value) -> bool {
    конфиг
        .get("outbounds")
        .and_then(|o| o.as_array())
        .map(|список| {
            !список.iter().any(|узел| {
                узел
                    .get("settings")
                    .and_then(|н| н.get("vnext"))
                    .and_then(|v| v.as_array())
                    .map(|адреса| {
                        адреса.iter().any(|а| {
                            !matches!(
                                а.get("address").and_then(|x| x.as_str()),
                                None | Some("0.0.0.0") | Some("")
                            )
                        })
                    })
                    .unwrap_or(false)
            })
        })
        .unwrap_or(true)
}

/// FastAPI кладёт текст ошибки в `detail`, а часть ручек — в `message`.
fn сообщение_сервера(данные: &Value) -> Option<String> {
    for ключ in ["detail", "message"] {
        if let Some(текст) = данные.get(ключ).and_then(|v| v.as_str()) {
            if !текст.is_empty() {
                return Some(текст.to_string());
            }
        }
    }
    None
}

