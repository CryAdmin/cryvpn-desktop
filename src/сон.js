// Сон окна: пока его никто не видит, оно ничего не рисует.
//
// Спрятанное к часам окно продолжало жить как открытое: робот «дышал»,
// ореол мерцал, часы перерисовывались каждую секунду. Системе при этом
// никто не говорил, что смотреть некому, и встроенный браузер рисовал всё
// это в пустоту. 15.11.2026 замер на компьютере владельца во время игры
// показал: спрятанное окно CryVPN занимает около 45% одного ядра
// процессора. Для игры это лишняя нагрузка на ровном месте.
//
// Теперь окно узнаёт, что его спрятали или свернули, и замирает: анимации
// встают на паузу, цифры не обновляются. Туннель при этом работает как
// работал — он от окна не зависит. Показали окно — всё оживает.
import { listen } from "@tauri-apps/api/event";

let спрятано = false;

/** Видит ли сейчас кто-нибудь окно. */
export const спит = () => спрятано || document.hidden;

const применить = () => {
  document.documentElement.classList.toggle("спит", спит());
};

/** Окно спрятали к часам или свернули (true) — или показали снова. */
export const уснуть = (да) => {
  спрятано = !!да;
  применить();
};

// О том, что окно спрятано к часам, сообщает само приложение: браузер
// внутри окна этого не замечает.
listen("сон", (событие) => уснуть(событие.payload)).catch(() => {});
document.addEventListener("visibilitychange", применить);
// Окно вернули на экран любым путём — значком, панелью задач, сочетанием
// клавиш — оно получает внимание. Это надёжный признак, что пора проснуться.
window.addEventListener("focus", () => уснуть(false));
