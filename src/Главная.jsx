import { useEffect, useRef, useState } from "react";
import { invoke } from "@tauri-apps/api/core";
import Флаг, { безФлага } from "./Флаг.jsx";
import Настройки from "./Настройки.jsx";

const ТЕЛЕФОН = navigator.userAgent.includes("Android");

// Какие туннели умеем. Готовый пока один — остальные помечены честно,
// чтобы человек не выбрал то, чего нет.
const ТУННЕЛИ = [
  { код: "xray", имя: "Xray", описание: "встроенный, по умолчанию", готов: true },
  { код: "singbox", имя: "sing-box", описание: "", готов: false },
  { код: "tun2socks", имя: "tun2socks", описание: "", готов: false },
];

const ВЫКЛ = "выкл";
const ЖДЁМ = "ждём";
const ВКЛ = "вкл";
const УХОДИМ = "уходим";

const дата = (строка) => {
  if (!строка) return null;
  const д = new Date(строка);
  return Number.isNaN(д.getTime())
    ? null
    : д.toLocaleDateString("ru-RU", { day: "numeric", month: "long", year: "numeric" });
};

const днейДо = (строка) => {
  if (!строка) return null;
  const осталось = new Date(строка) - new Date();
  return осталось > 0 ? Math.ceil(осталось / 86400000) : 0;
};

const скорость = (байтВСекунду) => {
  if (!байтВСекунду || байтВСекунду < 1) return "0 КБ/с";
  if (байтВСекунду < 1024 * 1024) return `${(байтВСекунду / 1024).toFixed(1)} КБ/с`;
  return `${(байтВСекунду / 1048576).toFixed(2)} МБ/с`;
};

const объём = (байт) => {
  if (!байт) return "0 КБ";
  if (байт < 1048576) return `${(байт / 1024).toFixed(0)} КБ`;
  if (байт < 1073741824) return `${(байт / 1048576).toFixed(1)} МБ`;
  if (байт < 1099511627776) return `${(байт / 1073741824).toFixed(1)} ГБ`;
  return `${(байт / 1099511627776).toFixed(2)} ТБ`;
};

// Цвет задержки: чтобы хороший сервер было видно без чтения цифр.
const оценка = (мс) => (мс < 0 ? "плохо" : мс < 200 ? "хорошо" : мс <= 400 ? "средне" : "плохо");

const часы = (секунд) => {
  const ч = Math.floor(секунд / 3600);
  const м = Math.floor((секунд % 3600) / 60);
  const с = секунд % 60;
  const дв = (н) => String(н).padStart(2, "0");
  return ч > 0 ? `${дв(ч)}:${дв(м)}:${дв(с)}` : `${дв(м)}:${дв(с)}`;
};

export default function Главная({ профиль, обновить, выйти, войтиПочтой }) {
  // Вошли по ссылке со страницы подписки — кабинета у нас нет, только сама
  // подписка. Срок тогда берём из её заголовков, а не из профиля.
  const безКабинета = !!профиль.только_подписка;
  const [выбран, выбрать] = useState(null);
  const [серверы, установитьСерверы] = useState([]);
  const [подписка_данные, установитьПодписку] = useState(null);
  const конец = безКабинета
    ? подписка_данные?.истекает
      ? new Date(подписка_данные.истекает * 1000).toISOString()
      : null
    : профиль.end_subscribe;
  const подписка = безКабинета ? !!подписка_данные : профиль.have_active_subscribe;
  const до = дата(конец);
  const дней = днейДо(конец);
  const [бедаСерверов, установитьБеду] = useState("");
  const [грузим, установитьЗагрузку] = useState(true);
  const [состояние, установитьСостояние] = useState(ВЫКЛ);
  const [ошибка, установитьОшибку] = useState("");
  const [секунды, установитьСекунды] = useState(0);
  const [темп, установитьТемп] = useState({ вверх: 0, вниз: 0 });
  const [всего, установитьВсего] = useState({ отдано: 0, принято: 0 });
  const [задержки, установитьЗадержки] = useState({});
  const [меряем, установитьЗамер] = useState(false);
  const [освежаем, установитьОсвежение] = useState(false);
  const [весть, установитьВесть] = useState(null);
  const гашение = useRef(null);
  const счётСверен = useRef(false);
  const чужойВидели = useRef(null);

  // Телефон: экран маленький, и под кнопкой помещалось два сервера. Когда
  // человек листает список, всё лишнее плавно уезжает, кнопка уменьшается,
  // и серверы поднимаются прямо к ней. Потянул вниз на самом верху списка —
  // всё возвращается. На компьютере этого нет: там места хватает.
  const [сжат, сжать] = useState(false);
  const список = useRef(null);
  const касание = useRef(null);
  const началоКасания = (е) => {
    касание.current = е.touches[0].clientY;
  };
  const ходКасания = (е) => {
    if (!ТЕЛЕФОН || касание.current === null) return;
    const сдвиг = е.touches[0].clientY - касание.current;
    const вверху = (список.current?.scrollTop ?? 0) <= 0;
    if (!сжат && сдвиг < -24) сжать(true);
    else if (сжат && вверху && сдвиг > 36) сжать(false);
  };
  const прокрутка = (е) => {
    if (ТЕЛЕФОН && !сжат && е.currentTarget.scrollTop > 8) сжать(true);
  };


  // Сообщение по центру экрана: что получилось или что именно сломалось.
  const сказать = (текст, вид = "удача") => {
    clearTimeout(гашение.current);
    установитьВесть({ текст, вид });
    гашение.current = setTimeout(() => установитьВесть(null), вид === "беда" ? 5200 : 2400);
  };
  const прошлое = useRef(null);
  const промахи = useRef(0);
  const тики = useRef(0);
  const [туннель, установитьТуннель] = useState("xray");
  const [списокТуннелей, показатьТуннели] = useState(false);
  const [настройкиОткрыты, показатьНастройки] = useState(false);



  // Есть ли у аккаунта действующая подписка. Смотрим на отдельное поле
  // кабинета, а не на ссылку: у истёкших подписок ссылка остаётся, и по ней
  // приложение показало бы человеку мёртвые серверы.
  const безПодписки = !профиль.только_подписка && профиль.have_active_subscribe === false;

  // Туннель мог пережить окно: на Android его держит отдельная служба.
  // Спрашиваем об этом сразу и отдельно от загрузки подписки. Раньше
  // состояние перенималось только после удачной загрузки, и если она
  // срывалась, экран показывал «Отключено» при работающем VPN — без способа
  // его выключить.
  useEffect(() => {
    invoke("подключено")
      .then((включён) => {
        if (включён) установитьСостояние((было) => (было === ВЫКЛ ? ВКЛ : было));
      })
      .catch(() => {});
  }, []);

  useEffect(() => {
    let живы = true;
    (async () => {
      установитьЗагрузку(true);
      установитьБеду("");
      if (безПодписки) {
        установитьСерверы([]);
        установитьПодписку(null);
        установитьБеду("У вас нет действующей подписки");
        установитьЗагрузку(false);
        return;
      }
      try {
        const данные = await invoke("серверы", { ссылка: профиль.subscriptionUrl ?? "" });
        if (!живы) return;
        установитьПодписку(данные);
        установитьСерверы(данные.серверы);
        // Если туннель уже работает, показываем тот сервер, через который
        // идёт трафик, а не первый в списке.
        const текущий = await invoke("текущий_сервер").catch(() => null);
        if (!живы) return;
        выбрать((прежний) => текущий ?? прежний ?? данные.серверы[0]?.номер ?? null);
        if (await invoke("подключено")) установитьСостояние(ВКЛ);
        // Устройство попадает в учёт кабинета в момент загрузки подписки,
        // то есть уже после того, как мы прочитали «N из M устройств».
        // Перечитываем профиль один раз, иначе цифра отстаёт на единицу.
        if (!счётСверен.current) {
          счётСверен.current = true;
          обновить?.().catch?.(() => {});
        }
      } catch (беда) {
        if (живы) установитьБеду(String(беда));
      } finally {
        if (живы) установитьЗагрузку(false);
      }
    })();
    return () => {
      живы = false;
    };
  }, [профиль.subscriptionUrl, безПодписки]);

  // Часы сессии и настоящие счётчики трафика из ядра. Цифры не выдуманные:
  // ядро считает их само, мы только спрашиваем раз в секунду.
  useEffect(() => {
    if (состояние !== ВКЛ) {
      установитьСекунды(0);
      установитьТемп({ вверх: 0, вниз: 0 });
      установитьВсего({ отдано: 0, принято: 0 });
      прошлое.current = null;
      return;
    }
    // Часы показывают, сколько работает сам туннель, а не сколько открыто
    // окно. Раньше счёт шёл в окне и начинался с нуля всякий раз, когда
    // Android выгружал приложение из памяти: человек играл, возвращался —
    // и видел «00:40», будто VPN только что переподключился.
    let начало = Date.now();
    let живы = true;
    invoke("идёт_секунд")
      .then((с) => {
        if (!живы) return;
        начало = Date.now() - с * 1000;
        установитьСекунды(с);
      })
      .catch(() => {});
    const таймер = setInterval(async () => {
      установитьСекунды(Math.max(0, Math.floor((Date.now() - начало) / 1000)));
      // Ядро могло упасть само. Тогда трафик уже идёт напрямую, и писать
      // «Подключено» — значит обманывать человека в самом важном.
      //
      // Но одному промаху не верим. На macOS жив ли туннель, узнаём по
      // ответу его порта, а порт может не успеть ответить, когда машина
      // занята. Один такой промах показывал «туннель оборвался» при живом
      // туннеле. Объявляем обрыв только после трёх промахов подряд.
      try {
        if (await invoke("подключено")) {
          промахи.current = 0;
        } else if (++промахи.current >= 3) {
          промахи.current = 0;
          установитьСостояние(ВЫКЛ);
          // Причину показываем как есть: без неё «оборвался» ничего не
          // объясняет ни человеку, ни нам.
          let причина = "";
          try {
            причина = (await invoke("причина_остановки")) ?? "";
          } catch {
            /* причины нет — покажем без неё */
          }
          invoke("отметить_обрыв", { причина: причина || null }).catch(() => {});
          // VPN выключили кнопкой в уведомлении или в настройках системы:
          // это решение человека, пугать его «обрывом» незачем.
          установитьОшибку(
            причина === "выключено-снаружи"
              ? ""
              : "Туннель оборвался. Трафик идёт напрямую — подключитесь заново" +
                  (причина ? `\n${причина}` : ""),
          );
          return;
        }
      } catch {
        /* не узнали — спросим через секунду */
      }
      // Раз в пять секунд смотрим, не включили ли другой VPN. Два туннеля
      // делят маршрут, и не работает ни один — поэтому наш уступает.
      тики.current += 1;
      if (тики.current % 5 === 0) {
        try {
          const чужой = await invoke("чужой_vpn");
          // Одному срабатыванию не верим: в момент, когда система
          // перестраивает сеть, проверка могла ошибиться, и приложение само
          // рвало исправный VPN. Отключаемся, только если чужой туннель
          // виден дважды подряд, с разницей в пять секунд.
          if (чужой && чужойВидели.current !== чужой) {
            чужойВидели.current = чужой;
          } else if (!чужой) {
            чужойВидели.current = null;
          } else {
            чужойВидели.current = null;
            await invoke("отключить", { причина: `чужой VPN: ${чужой}` });
            установитьСостояние(ВЫКЛ);
            установитьОшибку(
              `Включён другой VPN — ${чужой}. CryVPN отключён, чтобы они не мешали друг другу`,
            );
            return;
          }
        } catch {
          /* не узнали — проверим через пять секунд */
        }
      }
      try {
        const сейчас = await invoke("счётчики");
        if (прошлое.current) {
          установитьТемп({
            вверх: Math.max(0, сейчас.отдано - прошлое.current.отдано),
            вниз: Math.max(0, сейчас.принято - прошлое.current.принято),
          });
        }
        прошлое.current = сейчас;
        установитьВсего(сейчас);
      } catch {
        /* счётчики — не повод шуметь */
      }
    }, 1000);
    return () => clearInterval(таймер);
  }, [состояние]);

  // Подписку перечитываем с той частотой, которую назначила панель:
  // владелец меняет её у себя и ожидает, что клиенты послушаются.
  useEffect(() => {
    const часы = подписка_данные?.интервал_часов;
    if (!часы) return;
    const таймер = setInterval(async () => {
      try {
        const свежее = await invoke("серверы", { ссылка: профиль.subscriptionUrl ?? "" });
        принятьСписок(свежее);
      } catch {
        /* не достучались — попробуем в следующий раз */
      }
    }, часы * 3600 * 1000);
    return () => clearInterval(таймер);
  }, [подписка_данные?.интервал_часов, профиль.subscriptionUrl]);

  // Список взят из памяти: до панели не достучались. Стучимся снова раз в
  // полминуты — связь вернётся, и список освежится.
  useEffect(() => {
    if (!подписка_данные?.из_памяти) return undefined;
    const таймер = setInterval(async () => {
      try {
        const свежее = await invoke("серверы", { ссылка: профиль.subscriptionUrl ?? "" });
        if (!свежее.из_памяти) принятьСписок(свежее);
      } catch {
        /* всё ещё нет связи */
      }
    }, 30000);
    return () => clearInterval(таймер);
  }, [подписка_данные?.из_памяти, профиль.subscriptionUrl]);

  const замерить = async () => {
    if (меряем) return;
    установитьЗамер(true);
    try {
      const мс = await invoke("пинг");
      установитьЗадержки(Object.fromEntries(мс.map((з, н) => [н, з ?? -1])));
    } catch {
      /* замер — не повод шуметь */
    } finally {
      установитьЗамер(false);
    }
  };

  // Кнопка обновления перечитывает и профиль, и подписку: человек ждёт
  // свежих серверов и свежего остатка трафика, а не одного из двух.
  const освежить = async () => {
    if (освежаем) return;
    установитьОсвежение(true);
    try {
      // Кабинет недоступен — это ещё не конец: список серверов берётся с
      // другого адреса, а не выйдет и там — скажем об этом одной фразой.
      await обновить().catch((беда) => {
        if (!String(беда).startsWith("Нет связи")) throw беда;
      });
      // Подписки нет — серверы перечитывать не из чего. Если её только что
      // купили, профиль обновится и список загрузится сам.
      if (безПодписки) return;
      const свежее = await invoke("серверы", { ссылка: профиль.subscriptionUrl ?? "" });
      принятьСписок(свежее);
      if (свежее.из_памяти) {
        сказать("Похоже, работают белые списки или нет интернета — подписку не обновить", "беда");
        return;
      }
      сказать(`Подписка обновлена · серверов: ${свежее.серверы.length}`);
    } catch (беда) {
      // Показываем причину как есть: её сообщает кабинет или панель.
      const текст = String(беда);
      сказать(текст.startsWith("Похоже") ? текст : `Не удалось обновить подписку: ${текст}`, "беда");
    } finally {
      установитьОсвежение(false);
    }
  };

  // После обновления подписки порядок серверов может поменяться. Выбор
  // держим по названию, а не по номеру в списке: иначе «Эстония» через час
  // молча превратилась бы в соседнюю строку.
  const живое = useRef({ серверы: [], выбран: null });
  живое.current = { серверы, выбран };
  const принятьСписок = (свежее) => {
    // Читаем через ссылку: часовой таймер держит старую копию функции,
    // и без этого сравнивал бы с выбором часовой давности.
    const { серверы: были, выбран: был } = живое.current;
    const прежнееИмя = были.find((с) => с.номер === был)?.имя;
    установитьПодписку(свежее);
    установитьСерверы(свежее.серверы);
    // Номера серверов могли сдвинуться: прежние замеры встали бы не к тем.
    const тотЖеСостав =
      были.length === свежее.серверы.length &&
      были.every((с, н) => с.имя === свежее.серверы[н]?.имя);
    if (!тотЖеСостав) установитьЗадержки({});
    if (прежнееИмя) {
      const тотЖе = свежее.серверы.find((с) => с.имя === прежнееИмя);
      выбрать(тотЖе ? тотЖе.номер : (свежее.серверы[0]?.номер ?? null));
    }
  };

  const подключить = async (номер) => {
    установитьОшибку("");
    установитьСостояние(ЖДЁМ);
    try {
      await invoke("подключить", { номер });
      установитьСостояние(ВКЛ);
    } catch (беда) {
      установитьСостояние(ВЫКЛ);
      установитьОшибку(String(беда));
    }
  };

  const переключить = async () => {
    if (состояние === ЖДЁМ || состояние === УХОДИМ) return;
    if (состояние === ВКЛ) {
      установитьСостояние(УХОДИМ);
      try {
        await invoke("отключить", { причина: "кнопка в приложении" });
      } finally {
        установитьСостояние(ВЫКЛ);
      }
      return;
    }
    if (выбран === null) {
      установитьОшибку("Сначала выберите сервер");
      return;
    }
    await подключить(выбран);
  };

  const выбратьСервер = async (номер) => {
    // Пока идёт подключение или отключение, выбор не трогаем: иначе на
    // экране оказался бы один сервер, а трафик шёл бы через другой.
    if (состояние === ЖДЁМ || состояние === УХОДИМ) return;
    выбрать(номер);
    if (состояние === ВКЛ) await подключить(номер);
  };

  const выбранный = серверы.find((с) => с.номер === выбран);

  return (
    <main
      className={`экран ${сжат ? "сжат" : ""}`}
      onTouchStart={началоКасания}
      onTouchMove={ходКасания}
    >
      {настройкиОткрыты && <Настройки закрыть={() => показатьНастройки(false)} />}
      <header className="шапка">
        <div className="шапка-лево">
          <button
            className="шестерня"
            onClick={() => показатьНастройки(true)}
            title="Настройки"
            aria-label="Настройки"
          >
            <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true">
              <path
                fill="none"
                stroke="currentColor"
                strokeWidth="1.8"
                strokeLinecap="round"
                strokeLinejoin="round"
                d="M12 15.2a3.2 3.2 0 1 0 0-6.4 3.2 3.2 0 0 0 0 6.4Zm7.4-3.2c0-.5 0-.9-.1-1.3l2-1.5-2-3.4-2.3.9c-.7-.6-1.5-1-2.3-1.3L14.3 3h-4l-.4 2.4c-.8.3-1.6.7-2.3 1.3l-2.3-.9-2 3.4 2 1.5c-.1.4-.1.8-.1 1.3s0 .9.1 1.3l-2 1.5 2 3.4 2.3-.9c.7.6 1.5 1 2.3 1.3l.4 2.4h4l.4-2.4c.8-.3 1.6-.7 2.3-1.3l2.3.9 2-3.4-2-1.5c.1-.4.1-.8.1-1.3Z"
              />
            </svg>
          </button>
        </div>
        <div className="шапка-право">
          <span className="тускло">
            {безКабинета ? (
              <button className="значок" onClick={войтиПочтой} title="Оплата и устройства — в кабинете">
                Войти почтой
              </button>
            ) : (
              `${профиль.connected_devices_count ?? 0} из ${профиль.device_limit ?? 0} устройств`
            )}
          </span>
          <button className="значок" onClick={выйти} title="Выйти из профиля">
            Выйти
          </button>
        </div>
      </header>

      <div className="верх">
      <div className="режимы">
        <button
          className={`режим выбран ${списокТуннелей ? "раскрыт" : ""}`}
          onClick={() => показатьТуннели((в) => !в)}
          title="Выбрать туннель"
        >
          TUN · {ТУННЕЛИ.find((т) => т.код === туннель)?.имя} ▾
        </button>

        {/* Меню всплывает поверх экрана и ничего под собой не сдвигает */}
        {списокТуннелей && (
          <>
            <div className="подложка" onClick={() => показатьТуннели(false)} />
            <ul className="выбор-туннеля">
              {ТУННЕЛИ.map((т) => (
                <li
                  key={т.код}
                  className={`туннель ${т.код === туннель ? "выбран" : ""} ${т.готов ? "" : "скоро"}`}
                  onClick={() => {
                    if (!т.готов) return;
                    установитьТуннель(т.код);
                    показатьТуннели(false);
                  }}
                >
                  <span>{т.имя}</span>
                  <span className="тускло">{т.готов ? т.описание : "скоро"}</span>
                </li>
              ))}
            </ul>
          </>
        )}
      </div>

      <div className="показания">
        <span className="темп вверх">
          <b>↑ {скорость(темп.вверх)}</b>
          <i>отдано {объём(всего.отдано)}</i>
        </span>
        <span className="темп часы">{состояние === ВКЛ ? часы(секунды) : "--:--"}</span>
        <span className="темп вниз">
          <b>↓ {скорость(темп.вниз)}</b>
          <i>принято {объём(всего.принято)}</i>
        </span>
      </div>

      <section className="пульт">
        <button
          className={`круг ${состояние}`}
          onClick={переключить}
          disabled={состояние === ЖДЁМ || состояние === УХОДИМ}
          title={состояние === ВКЛ ? "Отключить" : "Подключить"}
        >
          <span className="волна одна" />
          <span className="волна две" />
          <span className="ореол" />
<svg className="щит" viewBox="0 0 64 66" aria-hidden="true">
            <defs>
              <linearGradient id="металл" x1="0" y1="0" x2="1" y2="1">
                <stop offset="0" stopColor="currentColor" stopOpacity="1" />
                <stop offset="0.55" stopColor="currentColor" stopOpacity="0.82" />
                <stop offset="1" stopColor="currentColor" stopOpacity="0.55" />
              </linearGradient>
              <radialGradient id="блик" cx="0.34" cy="0.22" r="0.5">
                <stop offset="0" stopColor="#fff" stopOpacity="0.5" />
                <stop offset="1" stopColor="#fff" stopOpacity="0" />
              </radialGradient>
            </defs>
            {/* антенна с шариком */}
            <path d="M32.6 15 34 6.5" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" />
            <circle cx="34.3" cy="4.6" r="3.4" fill="currentColor" />
            <ellipse cx="32" cy="15.4" rx="5.6" ry="2.2" fill="currentColor" />
            {/* шлем: купол сверху, ровный низ */}
            <path
              d="M11 56V34a21 21 0 0 1 42 0v22q0 5-5 5H16q-5 0-5-5Z"
              fill="url(#металл)"
            />
            <path d="M11 56V34a21 21 0 0 1 42 0v22q0 5-5 5H16q-5 0-5-5Z" fill="url(#блик)" />
            {/* глаза-отверстия */}
            <circle className="глаз" cx="23" cy="36" r="6" fill="#0a0d12" />
            <circle className="глаз" cx="41" cy="36" r="6" fill="#0a0d12" />
            {/* рот: улыбка, ровный и грустный — показывается нужный */}
            <path className="рот улыбка" d="M19 46q13 12 26 0" />
            <path className="рот ровный" d="M22 50h20" />
            <path className="рот грусть" d="M20 53q12-11 24 0" />
            {/* слеза — только когда отключено */}
            <path className="слеза" d="M41 44.5c-1.7 2.4-2.4 3.7-2.4 4.8a2.4 2.4 0 0 0 4.8 0c0-1.1-.7-2.4-2.4-4.8Z" />
          </svg>
        </button>

        <p className={`состояние ${состояние}`}>
          {состояние === ВКЛ
            ? "Подключено"
            : состояние === ЖДЁМ
              ? "Подключаемся…"
              : состояние === УХОДИМ
                ? "Отключаемся…"
                : "Отключено"}
        </p>

        {выбранный && (
          <p className="выбранный">
            <Флаг имя={выбранный.имя} />
            <span>{безФлага(выбранный.имя)}</span>
          </p>
        )}

        <p className="строка мелко">
          {подписка
            ? дней !== null
              ? `Подписка активна${профиль.is_premium ? " · премиум" : ""}`
              : "Подписка активна"
            : "Подписки нет"}
        </p>
        {подписка_данные?.всего > 0 && (
          <div className="трафик" title="Лимит трафика на месяц из панели">
            <div className="трафик-строка">
              <span>
                Осталось{" "}
                <b>{объём(Math.max(0, подписка_данные.всего - подписка_данные.потрачено))}</b>
              </span>
              <span className="тускло">
                потрачено {объём(подписка_данные.потрачено)} из {объём(подписка_данные.всего)}
              </span>
            </div>
            <div className="полоса">
              <div
                className="полоса-заполнено"
                style={{
                  width: `${Math.min(100, (подписка_данные.потрачено / подписка_данные.всего) * 100)}%`,
                }}
              />
            </div>
          </div>
        )}
        {ошибка && <p className="беда">{ошибка}</p>}
      </section>

      {(подписка_данные?.объявление || весть) && (
        <div className="место-объявления">
          {подписка_данные?.объявление && (
            <div className="объявление">
              {подписка_данные.объявление.split("\n").map((строка, н) => (
                <p key={н}>{строка}</p>
              ))}
            </div>
          )}
          {/* Итог обновления накрывает объявление и сам исчезает */}
          {весть && (
            <div className={`весть ${весть.вид}`} onClick={() => установитьВесть(null)}>
              <span className="весть-знак">{весть.вид === "беда" ? "!" : "✓"}</span>
              <span>{весть.текст}</span>
            </div>
          )}
        </div>
      )}

      {(подписка_данные?.сайт || подписка_данные?.объявление_ссылка) && (
        <div className="ссылки">
          {подписка_данные.сайт && (
            <button
              className="ссылка"
              onClick={() => invoke("открыть_ссылку", { адрес: подписка_данные.сайт })}
            >
              Сайт CryVPN
            </button>
          )}
          {подписка_данные.объявление_ссылка && (
            <button
              className="ссылка"
              onClick={() =>
                invoke("открыть_ссылку", { адрес: подписка_данные.объявление_ссылка })
              }
            >
              Бот в Telegram
            </button>
          )}
        </div>
      )}

      </div>

      <section className="блок">
        <div className="блок-шапка">
          <span>Серверы</span>
          <span className="блок-кнопки">
            <button
              className={`круглая ${освежаем ? "освежает" : ""}`}
              onClick={освежить}
              title="Обновить подписку"
              aria-label="Обновить подписку"
            >
              <svg
                className={освежаем ? "вращение" : ""}
                viewBox="0 0 24 24"
                width="16"
                height="16"
                aria-hidden="true"
              >
                <path
                  d="M20 11a8 8 0 0 0-14.3-4.3L4 8.5M4 4v4.5h4.5M4 13a8 8 0 0 0 14.3 4.3L20 15.5M20 20v-4.5h-4.5"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              </svg>
            </button>
            <button
              className={`круглая ${меряем ? "меряет" : ""}`}
              onClick={замерить}
              title="Замерить задержку до серверов"
              aria-label="Замерить задержку"
            >
              <svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true">
                <path
                  d="M3 12h4l2.5-6 4 12 2.5-6H21"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              </svg>
            </button>
          </span>
        </div>

        {(подписка_данные?.из_памяти || профиль.без_связи) && !грузим && !бедаСерверов && (
          <p className="строка мелко">
            Похоже, работают белые списки или нет интернета — подписку не обновить. Показаны сохранённые серверы
          </p>
        )}
        {грузим ? (
          <p className="строка">Читаем подписку…</p>
        ) : бедаСерверов ? (
          <p className="беда">{бедаСерверов}</p>
        ) : серверы.length === 0 ? (
          <p className="строка">В подписке нет ни одного сервера</p>
        ) : (
          <ul className="список" ref={список} onScroll={прокрутка}>
            {серверы.map((с) => (
              <li
                key={с.номер}
                className={с.номер === выбран ? "сервер выбран" : "сервер"}
                onClick={() => выбратьСервер(с.номер)}
                style={{ animationDelay: `${Math.min(с.номер, 12) * 28}ms` }}
              >
                <Флаг имя={с.имя} />
                <span className="сервер-имя">{безФлага(с.имя)}</span>
                {задержки[с.номер] !== undefined && (
                  <span className={`задержка ${оценка(задержки[с.номер])}`}>
                    {задержки[с.номер] < 0 ? "нет ответа" : `${задержки[с.номер]} мс`}
                  </span>
                )}
              </li>
            ))}
          </ul>
        )}
      </section>
    </main>
  );
}
