const часы = (секунд) => {
  const ч = Math.floor(секунд / 3600);
  const м = Math.floor((секунд % 3600) / 60);
  const с = секунд % 60;
  const дв = (н) => String(н).padStart(2, "0");
  return ч > 0 ? `${дв(ч)}:${дв(м)}:${дв(с)}` : `${дв(м)}:${дв(с)}`;
};

/**
 * Объявление из панели подписки.
 *
 * Высота у него ограничена, чтобы не вытеснять список серверов. Раньше
 * лишнее пряталось под прокрутку без полосы: на узком экране текст
 * обрезался, и никто не догадывался, что блок крутится (жалоба
 * 18.11.2026), а пультом телевизора его не прокрутить вовсе. Теперь, если
 * текст не влез, внизу затухание и «Показать всё» — нажатие или ОК на
 * пульте раскрывает объявление целиком.
 */
function Объявление({ текст }) {
  const блок = useRef(null);
  const [развёрнуто, развернуть] = useState(false);
  const [не_влезает, отметить] = useState(false);

  useEffect(() => {
    const измерить = () => {
      const э = блок.current;
      if (э && !развёрнуто) отметить(э.scrollHeight > э.clientHeight + 2);
    };
    измерить();
    window.addEventListener("resize", измерить);
    return () => window.removeEventListener("resize", измерить);
  }, [текст, развёрнуто]);

  const переключить = () => {
    if (не_влезает || развёрнуто) развернуть((б) => !б);
  };

  return (
    <div
      ref={блок}
      className={`объявление ${развёрнуто ? "развёрнуто" : ""} ${не_влезает && !развёрнуто ? "обрезано" : ""}`}
      onClick={переключить}
      tabIndex={не_влезает || развёрнуто ? 0 : -1}
      role={не_влезает || развёрнуто ? "button" : undefined}
      onKeyDown={(е) => {
        if (е.key === "Enter" || е.key === " ") {
          е.preventDefault();
          переключить();
        }
      }}
    >
      {текст.split("\n").map((строка, н) => (
        <p key={н}>{строка}</p>
      ))}
      {не_влезает && !развёрнуто && <span className="объявление-ещё">Показать всё ▾</span>}
      {развёрнуто && <span className="объявление-ещё">Свернуть ▴</span>}
    </div>
  );
}

