import { useEffect, useRef, useState } from "react";
import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import "./App.css";
import Вход from "./Вход.jsx";
import Главная from "./Главная.jsx";

// Профиль для того, кто вошёл по ссылке со страницы подписки. Кабинета у
// него нет — есть только сама подписка, и этого хватает для серверов.
const безКабинета = (адрес) => ({ только_подписка: true, subscriptionUrl: адрес });

export default function App() {
  const [профиль, установитьПрофиль] = useState(null);
  const [проверяем, установитьПроверку] = useState(true);
  const [весть, установитьВесть] = useState("");
  // Токен из ссылки входа, который ждёт согласия человека.
  const [запросВхода, установитьЗапросВхода] = useState(null);
  // Свежий профиль для обработчика ссылок: он живёт дольше одного кадра.
  const профильСейчас = useRef(null);
  профильСейчас.current = профиль;

  // Что показать при открытии, по убыванию важности:
  //   1. только что нажатая ссылка cryvpn:// — человек явно этого хотел;
  //   2. сохранённый вход в кабинет — там есть оплата и устройства;
  //   3. подписка, сохранённая с прошлой ссылки;
  //   4. экран входа.
  // Ссылка входа из кабинета: одноразовый токен меняем на вход. Сеть могла
  // моргнуть — пробуем несколько раз, прежде чем сдаться: токен на сервере
  // жив две минуты, а второго у приложения нет.
  const войтиПоСсылке = async (токен) => {
    for (let попытка = 0; попытка < 4; попытка += 1) {
      const опрос = await invoke("телеграм_опрос", { токен });
      if (опрос.состояние === "вошли") {
        установитьПрофиль(await invoke("профиль"));
        return true;
      }
      if (опрос.состояние === "отказ") {
        установитьВесть(опрос.сообщение);
        return false;
      }
      await new Promise((готово) => setTimeout(готово, 1500));
    }
    установитьВесть("Не удалось войти по ссылке: нет связи. Нажмите кнопку в кабинете ещё раз");
    return false;
  };

  const определиться = async () => {
    try {
      const токен = await invoke("вход_по_ссылке");
      if (токен) {
        // Приложение уже в чьём-то аккаунте — без спроса его не меняем.
        // Иначе любая страница могла бы ссылкой молча пересадить человека в
        // чужой кабинет. Если входа ещё нет, спрашивать не о чем: человек
        // сам только что нажал кнопку в кабинете.
        if (профильСейчас.current) {
          установитьЗапросВхода(токен);
          return;
        }
        if (await войтиПоСсылке(токен)) return;
      }
      const поСсылке = await invoke("подписка_по_ссылке");
      if (поСсылке?.свежая) {
        установитьПрофиль(безКабинета(поСсылке.адрес));
        return;
      }
      // Вход жив, а до кабинета не достучаться — так бывает в сети, где
      // открываются только разрешённые сайты. Экран входа тут был бы
      // обманом: человек вошёл, и войти заново всё равно не сможет.
      // Показываем то, что помним с прошлого раза: с сохранённым списком
      // серверов можно подключиться и без кабинета.
      const вход = await invoke("восстановить");
      if (вход !== "нет") {
        const свежий = вход === "вошли" ? await invoke("профиль").catch(() => null) : null;
        const старый = свежий ? null : await invoke("профиль_из_памяти");
        if (свежий || старый) {
          установитьПрофиль(свежий ?? { ...старый, без_связи: true });
          return;
        }
        установитьВесть("Похоже, работают белые списки или нет интернета — до кабинета не достучаться");
      }
      if (поСсылке) установитьПрофиль(безКабинета(поСсылке.адрес));
    } catch {
      /* не вышло — покажем вход */
    } finally {
      установитьПроверку(false);
    }
  };

  useEffect(() => {
    определиться();
    // Ссылку могли нажать, когда приложение уже открыто.
    const отписки = [
      listen("ссылка", () => определиться()),
      listen("ссылка-отвергнута", () =>
        установитьВесть("Ссылка не от CryVPN — подписку из неё не берём"),
      ),
    ];
    return () => отписки.forEach((о) => о.then((снять) => снять()));
  }, []);

  // Пока кабинет недоступен, тихо стучимся снова: связь вернётся — и
  // профиль обновится сам.
  useEffect(() => {
    if (!профиль?.без_связи) return undefined;
    const таймер = setInterval(async () => {
      try {
        if ((await invoke("восстановить")) === "вошли") установитьПрофиль(await invoke("профиль"));
      } catch {
        /* всё ещё нет связи — попробуем позже */
      }
    }, 20000);
    return () => clearInterval(таймер);
  }, [профиль?.без_связи]);

  const выйти = async () => {
    await invoke("выйти");
    await invoke("забыть_подписку");
    установитьПрофиль(null);
  };

  const обновить = async () => {
    if (профиль?.только_подписка) return;
    установитьПрофиль(await invoke("профиль"));
  };

  if (проверяем) {
    return (
      <main className="экран по-центру">
        <h1 className="знак">CryVPN</h1>
        <p className="строка">Проверяем вход…</p>
      </main>
    );
  }

  const вопросВхода = запросВхода && (
    <div className="затемнение">
      <div className="окошко">
        <div className="окошко-шапка">
          <span>Войти в другой аккаунт?</span>
        </div>
        <p className="строка">
          Пришла ссылка входа из кабинета. Приложение выйдет из текущего аккаунта и войдёт в тот,
          из которого она отправлена. Соглашайтесь, только если сами сейчас нажали кнопку в кабинете
        </p>
        <button
          className="кнопка"
          onClick={async () => {
            const токен = запросВхода;
            установитьЗапросВхода(null);
            await invoke("отключить", { причина: "смена аккаунта" }).catch(() => {});
            await войтиПоСсылке(токен);
          }}
        >
          Войти
        </button>
        <button className="кнопка второстепенная" onClick={() => установитьЗапросВхода(null)}>
          Отмена
        </button>
      </div>
    </div>
  );

  return профиль ? (
    <>
      {вопросВхода}
      {весть && <p className="беда внизу">{весть}</p>}
    <Главная
      профиль={профиль}
      обновить={обновить}
      выйти={выйти}
      войтиПочтой={async () => {
        // Уходим на экран входа — туннель гасим: с этого экрана его не
        // видно и не выключить, а после входа в другой аккаунт он шёл бы
        // по чужой подписке.
        await invoke("отключить", { причина: "смена аккаунта" }).catch(() => {});
        установитьПрофиль(null);
      }}
    />
    </>
  ) : (
    <>
      <Вход вошли={установитьПрофиль} />
      {весть && <p className="беда внизу">{весть}</p>}
    </>
  );
}
