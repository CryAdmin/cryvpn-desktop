import { useEffect, useState } from "react";
import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import "./App.css";
import Вход from "./Вход.jsx";
import Главная from "./Главная.jsx";

// Профиль для того, кто вошёл по ссылке со страницы подписки. Кабинета у
// него нет — есть только сама подписка, и этого хватает для серверов.
const безКабинета = (адрес) => ({ только_подписка: true, subscriptionUrl: адрес });

export default function App() {
  const [профиль, установитьПрофиль] = useState(null);
  const [проверяем, установитьПроверку] = useState(true);
  const [весть, установитьВесть] = useState("");

  // Что показать при открытии, по убыванию важности:
  //   1. только что нажатая ссылка cryvpn:// — человек явно этого хотел;
  //   2. сохранённый вход в кабинет — там есть оплата и устройства;
  //   3. подписка, сохранённая с прошлой ссылки;
  //   4. экран входа.
  const определиться = async () => {
    try {
      const поСсылке = await invoke("подписка_по_ссылке");
      if (поСсылке?.свежая) {
        установитьПрофиль(безКабинета(поСсылке.адрес));
        return;
      }
      if (await invoke("восстановить")) {
        установитьПрофиль(await invoke("профиль"));
        return;
      }
      if (поСсылке) установитьПрофиль(безКабинета(поСсылке.адрес));
    } catch {
      /* не вышло — покажем вход */
    } finally {
      установитьПроверку(false);
    }
  };

  useEffect(() => {
    определиться();
    // Ссылку могли нажать, когда приложение уже открыто.
    const отписки = [
      listen("ссылка", () => определиться()),
      listen("ссылка-отвергнута", () =>
        установитьВесть("Ссылка не от CryVPN — подписку из неё не берём"),
      ),
    ];
    return () => отписки.forEach((о) => о.then((снять) => снять()));
  }, []);

  const выйти = async () => {
    await invoke("выйти");
    await invoke("забыть_подписку");
    установитьПрофиль(null);
  };

  const обновить = async () => {
    if (профиль?.только_подписка) return;
    установитьПрофиль(await invoke("профиль"));
  };

  if (проверяем) {
    return (
      <main className="экран по-центру">
        <h1 className="знак">CryVPN</h1>
        <p className="строка">Проверяем вход…</p>
      </main>
    );
  }

  return профиль ? (
    <Главная
      профиль={профиль}
      обновить={обновить}
      выйти={выйти}
      войтиПочтой={() => установитьПрофиль(null)}
    />
  ) : (
    <>
      <Вход вошли={установитьПрофиль} />
      {весть && <p className="беда внизу">{весть}</p>}
    </>
  );
}
