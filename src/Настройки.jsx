import { useEffect, useState } from "react";
import { invoke } from "@tauri-apps/api/core";
import { getVersion } from "@tauri-apps/api/app";

// Автозапуск, трей и свёрнутое окно — понятия компьютера. На телефоне
// их нет, поэтому там эти переключатели не показываем.
const телефон = navigator.userAgent.includes("Android");
// iPhone: ни выбора приложений мимо VPN, ни автозапуска система не даёт.
// Защиту и DNS держит расширение VPN.
const айфон = /iPhone|iPad|iPod/.test(navigator.userAgent);
const виндовс = navigator.userAgent.includes("Windows");
// DNS туннеля: в Windows и на Android система берёт его у адаптера VPN,
// в Linux приложение само заворачивает запросы на выбранный адрес. На Mac
// туннель этого пока не умеет.
const естьДнс = телефон || виндовс || navigator.userAgent.includes("Linux");

// Памятка к защите от утечки: раскрывается по нажатию на «?» рядом с
// названием — без запроса места не занимает.
const ПАМЯТКА_ЗАЩИТЫ = [
  "🛡 Если VPN внезапно оборвётся, интернет встанет на паузу, а не пойдёт напрямую с вашим настоящим адресом",
  "✅ Полезно, когда важно не засветить свой IP: торренты, работа, сервисы, которые не должны видеть, где вы",
  "⏸ Пока VPN не подключится снова, интернета не будет. Снять паузу можно одной кнопкой на главном экране",
  // Windows пропускает домашнюю сеть (роутер, принтер) мимо защиты, Android
  // — нет: там защита держит туннель целиком. iPhone — только домашнюю сеть:
  // приложений мимо VPN там не бывает.
  телефон
    ? "🏠 Приложения из списка «Мимо VPN» работают всегда"
    : айфон
      ? "🏠 Домашняя сеть (роутер, принтер, AirPlay) работает всегда"
      : "🏠 Домашняя сеть и программы из списка «Мимо VPN» работают всегда",
];
// Защита от утечки сделана для Windows и Android.
const естьЗащита = телефон || виндовс;

/** Окошко настроек поверх главного экрана. */
export default function Настройки({ закрыть }) {
  const [свойства, установить] = useState(null);
  const [беда, установитьБеду] = useState("");
  const [версия, установитьВерсию] = useState("");

  useEffect(() => {
    getVersion().then(установитьВерсию).catch(() => {});
  }, []);

  useEffect(() => {
    (async () => {
      try {
        установить(await invoke("настройки"));
      } catch (е) {
        установитьБеду(String(е));
      }
    })();
  }, []);

  const поменять = async (ключ, значение) => {
    const новые = { ...свойства, [ключ]: значение };
    установить(новые);
    try {
      await invoke("сохранить_настройки", { новые });
    } catch (е) {
      установитьБеду(String(е));
    }
  };

  return (
    <div className="затемнение" onClick={закрыть}>
      <div className="окошко" onClick={(е) => е.stopPropagation()}>
        <div className="окошко-шапка">
          <span>Настройки</span>
          <button className="значок" onClick={закрыть}>
            Закрыть
          </button>
        </div>

        {!свойства ? (
          <p className="строка">Читаем настройки…</p>
        ) : айфон ? (
          <>
            <Переключатель
              имя="Защита от утечки (kill switch)"
              пояснение="При обрыве VPN интернет ждёт, а не идёт напрямую"
              памятка={ПАМЯТКА_ЗАЩИТЫ}
              включено={свойства.защита}
              поменять={(з) => поменять("защита", з)}
            />
            <Днс выбор={свойства.днс ?? ""} поменять={(з) => поменять("днс", з)} />
          </>
        ) : телефон ? (
          <>
            <Переключатель
              имя="Защита от утечки (kill switch)"
              пояснение="При обрыве VPN интернет ждёт, а не идёт напрямую"
              памятка={ПАМЯТКА_ЗАЩИТЫ}
              включено={свойства.защита}
              поменять={(з) => поменять("защита", з)}
            />
            <МимоVpn
              список={свойства.мимо_vpn ?? []}
              поменять={(з) => поменять("мимо_vpn", з)}
            />
            <Днс выбор={свойства.днс ?? ""} поменять={(з) => поменять("днс", з)} />
          </>
        ) : (
          <>
            <Переключатель
              имя={виндовс ? "Запускать вместе с Windows" : "Запускать вместе с системой"}
              пояснение="Приложение будет стартовать при входе в систему"
              включено={свойства.с_виндой}
              поменять={(з) => поменять("с_виндой", з)}
            />
            <Переключатель
              имя="Закрывать в трей"
              пояснение="Крестик сворачивает окно к часам, VPN продолжает работать. Выйти совсем — через значок"
              включено={свойства.в_трее}
              поменять={(з) => поменять("в_трее", з)}
            />
            {естьЗащита && (
              <Переключатель
                имя="Защита от утечки (kill switch)"
                пояснение="При обрыве VPN интернет ждёт, а не идёт напрямую"
                памятка={ПАМЯТКА_ЗАЩИТЫ}
                включено={свойства.защита}
                поменять={(з) => поменять("защита", з)}
              />
            )}
            <МимоVpn
              список={свойства.мимо_vpn ?? []}
              поменять={(з) => поменять("мимо_vpn", з)}
            />
            {естьДнс && <Днс выбор={свойства.днс ?? ""} поменять={(з) => поменять("днс", з)} />}
          </>
        )}

        {беда && <p className="беда">{беда}</p>}
        {версия && <p className="версия-приложения">CryVPN {версия}</p>}
      </div>
    </div>
  );
}

function Переключатель({ имя, пояснение, памятка, включено, поменять }) {
  // Памятка раскрывается и сворачивается нажатием на «?».
  const [открыта, открыть] = useState(false);
  return (
    <div className={памятка ? "с-памяткой" : undefined}>
      <label className="настройка">
        <span className="настройка-текст">
          <span className="настройка-имя">
            {имя}
            {памятка && (
              <button
                type="button"
                className="знак-памятки"
                aria-label="Что это"
                title="Что это и зачем"
                aria-expanded={открыта}
                onClick={(е) => {
                  е.preventDefault();
                  открыть(!открыта);
                }}
              >
                ?
              </button>
            )}
          </span>
          <span className="настройка-пояснение">{пояснение}</span>
        </span>
        <input
          type="checkbox"
          className="галка"
          checked={!!включено}
          onChange={(е) => поменять(е.target.checked)}
        />
      </label>
      {памятка && (
        <div className={`памятка ${открыта ? "открыта" : ""}`} role="note">
          {памятка.map((строка) => (
            <p key={строка}>{строка}</p>
          ))}
        </div>
      )}
    </div>
  );
}

const ГОТОВЫЕ_ДНС = [
  { ключ: "", имя: "По умолчанию" },
  { ключ: "google", имя: "Google" },
  { ключ: "adguard", имя: "AdGuard" },
];

/**
 * Каким DNS пользуется туннель. Нужен редко: некоторым играм и сервисам
 * не подходит ответ обычного DNS. Настройки самой системы приложение не
 * трогает — выбор действует только внутри VPN и только пока он включён.
 * Вернуть как было — одно нажатие на «По умолчанию».
 */
function Днс({ выбор, поменять }) {
  const готовый = ГОТОВЫЕ_ДНС.some((в) => в.ключ === выбор);
  // «Свой» открыт, если адрес уже записан или человек только что нажал.
  const [свой, открытьСвой] = useState(!готовый);
  const [адрес, установитьАдрес] = useState(готовый ? "" : выбор);
  const [беда, установитьБеду] = useState("");

  const взять = (ключ) => {
    открытьСвой(false);
    установитьБеду("");
    поменять(ключ);
  };

  const сохранить = () => {
    const чистый = адрес.trim();
    const части = чистый.split(/[\s,;]+/).filter(Boolean);
    const верный = (ч) =>
      /^\d{1,3}(\.\d{1,3}){3}$/.test(ч) && ч.split(".").every((н) => Number(н) <= 255);
    if (части.length < 1 || части.length > 2 || !части.every(верный)) {
      установитьБеду("Нужен адрес вида 8.8.8.8, можно два через запятую");
      return;
    }
    установитьБеду("");
    поменять(части.join(", "));
  };

  return (
    <section className="мимо">
      <div className="настройка-текст">
        <span className="настройка-имя">DNS в туннеле</span>
        <span className="настройка-пояснение">
          Действует только внутри VPN, настройки системы не меняются. Применится при следующем
          подключении
        </span>
      </div>

      <div className="днс-выбор">
        {ГОТОВЫЕ_ДНС.map((в) => (
          <button
            key={в.ключ}
            className={`кнопка-шапки ${!свой && выбор === в.ключ ? "выбрана" : ""}`}
            onClick={() => взять(в.ключ)}
          >
            {в.имя}
          </button>
        ))}
        <button
          className={`кнопка-шапки ${свой ? "выбрана" : ""}`}
          onClick={() => открытьСвой(true)}
        >
          Свой
        </button>
      </div>

      {свой && (
        <div className="днс-свой">
          <input
            className="поле мелкое"
            placeholder="Например, 8.8.8.8"
            inputMode="decimal"
            value={адрес}
            onChange={(е) => установитьАдрес(е.target.value)}
            onKeyDown={(е) => е.key === "Enter" && сохранить()}
          />
          <button className="кнопка-шапки" onClick={сохранить}>
            {!готовый && выбор === адрес.trim() ? "Сохранён" : "Сохранить"}
          </button>
        </div>
      )}
      {беда && <p className="беда">{беда}</p>}
      {(свой || выбор !== "") && (
        <p className="строка мелко">
          Сайты перестали открываться — нажмите «По умолчанию»
        </p>
      )}
    </section>
  );
}

/**
 * Программы, которые идут мимо VPN: их трафик уходит напрямую, всё
 * остальное — через туннель. На компьютере выбираем из запущенных программ
 * или указываем файл, на телефоне — из установленных приложений.
 */
function МимоVpn({ список, поменять }) {
  const [выбор, показатьВыбор] = useState(null); // null — закрыт, иначе найденные программы
  const [ищем, установитьПоиск] = useState(false);
  const [отбор, установитьОтбор] = useState("");

  const добавить = (программа) => {
    if (!программа || список.some((п) => п.путь === программа.путь)) return;
    поменять([...список, программа]);
  };

  const открытьВыбор = async () => {
    установитьПоиск(true);
    установитьОтбор("");
    try {
      показатьВыбор(await invoke("запущенные_программы"));
    } catch {
      показатьВыбор([]);
    } finally {
      установитьПоиск(false);
    }
  };

  const указатьФайл = async () => {
    try {
      добавить(await invoke("выбрать_программу"));
    } catch {
      /* человек закрыл окно выбора */
    }
  };

  const подходящие = (выбор ?? []).filter(
    (п) =>
      !список.some((с) => с.путь === п.путь) &&
      (п.имя + " " + п.путь).toLowerCase().includes(отбор.trim().toLowerCase()),
  );

  return (
    <section className="мимо">
      <div className="настройка-текст">
        <span className="настройка-имя">{телефон ? "Приложения мимо VPN" : "Программы мимо VPN"}</span>
        <span className="настройка-пояснение">
          Их трафик пойдёт напрямую, всё остальное — через VPN. Изменения применятся при следующем
          подключении
        </span>
      </div>

      {список.length > 0 && (
        <ul className="мимо-список">
          {список.map((п) => (
            <li key={п.путь} className="мимо-строка" title={п.путь}>
              <span className="мимо-имя">{п.имя}</span>
              <button
                className="мимо-убрать"
                onClick={() => поменять(список.filter((с) => с.путь !== п.путь))}
                aria-label={`Убрать ${п.имя}`}
              >
                ×
              </button>
            </li>
          ))}
        </ul>
      )}

      {выбор === null ? (
        <div className="мимо-кнопки">
          <button className="кнопка-шапки" onClick={открытьВыбор} disabled={ищем}>
            {ищем ? "Ищем…" : телефон ? "Добавить приложение" : "Добавить из запущенных"}
          </button>
          {!телефон && (
            <button className="кнопка-шапки" onClick={указатьФайл}>
              Указать файл…
            </button>
          )}
        </div>
      ) : (
        <div className="мимо-выбор">
          <input
            className="поле мелкое"
            placeholder="Найти по названию"
            value={отбор}
            onChange={(е) => установитьОтбор(е.target.value)}
          />
          <ul className="мимо-найдено">
            {подходящие.length === 0 && <li className="строка мелко">Ничего не найдено</li>}
            {подходящие.map((п) => (
              <li key={п.путь}>
                <button className="мимо-вариант" onClick={() => добавить(п)} title={п.путь}>
                  {п.имя}
                </button>
              </li>
            ))}
          </ul>
          <button className="кнопка второстепенная" onClick={() => показатьВыбор(null)}>
            Готово
          </button>
        </div>
      )}
    </section>
  );
}
