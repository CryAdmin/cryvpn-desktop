import { useEffect, useState } from "react";
import { invoke } from "@tauri-apps/api/core";
import { getVersion } from "@tauri-apps/api/app";

// Автозапуск, трей и свёрнутое окно — понятия компьютера. На телефоне
// их нет, поэтому там эти переключатели не показываем.
const телефон = navigator.userAgent.includes("Android");
const виндовс = navigator.userAgent.includes("Windows");

/** Окошко настроек поверх главного экрана. */
export default function Настройки({ закрыть }) {
  const [свойства, установить] = useState(null);
  const [беда, установитьБеду] = useState("");
  const [версия, установитьВерсию] = useState("");

  useEffect(() => {
    getVersion().then(установитьВерсию).catch(() => {});
  }, []);

  useEffect(() => {
    (async () => {
      try {
        установить(await invoke("настройки"));
      } catch (е) {
        установитьБеду(String(е));
      }
    })();
  }, []);

  const поменять = async (ключ, значение) => {
    const новые = { ...свойства, [ключ]: значение };
    установить(новые);
    try {
      await invoke("сохранить_настройки", { новые });
    } catch (е) {
      установитьБеду(String(е));
    }
  };

  return (
    <div className="затемнение" onClick={закрыть}>
      <div className="окошко" onClick={(е) => е.stopPropagation()}>
        <div className="окошко-шапка">
          <span>Настройки</span>
          <button className="значок" onClick={закрыть}>
            Закрыть
          </button>
        </div>

        {!свойства ? (
          <p className="строка">Читаем настройки…</p>
        ) : телефон ? (
          <МимоVpn
            список={свойства.мимо_vpn ?? []}
            поменять={(з) => поменять("мимо_vpn", з)}
          />
        ) : (
          <>
            <Переключатель
              имя={виндовс ? "Запускать вместе с Windows" : "Запускать вместе с системой"}
              пояснение="Приложение будет стартовать при входе в систему"
              включено={свойства.с_виндой}
              поменять={(з) => поменять("с_виндой", з)}
            />
            <Переключатель
              имя="Закрывать в трей"
              пояснение="Крестик сворачивает окно к часам, VPN продолжает работать. Выйти совсем — через значок"
              включено={свойства.в_трее}
              поменять={(з) => поменять("в_трее", з)}
            />
            <МимоVpn
              список={свойства.мимо_vpn ?? []}
              поменять={(з) => поменять("мимо_vpn", з)}
            />
          </>
        )}

        {беда && <p className="беда">{беда}</p>}
        {версия && <p className="версия-приложения">CryVPN {версия}</p>}
      </div>
    </div>
  );
}

function Переключатель({ имя, пояснение, включено, поменять }) {
  return (
    <label className="настройка">
      <span className="настройка-текст">
        <span className="настройка-имя">{имя}</span>
        <span className="настройка-пояснение">{пояснение}</span>
      </span>
      <input
        type="checkbox"
        className="галка"
        checked={!!включено}
        onChange={(е) => поменять(е.target.checked)}
      />
    </label>
  );
}

/**
 * Программы, которые идут мимо VPN: их трафик уходит напрямую, всё
 * остальное — через туннель. На компьютере выбираем из запущенных программ
 * или указываем файл, на телефоне — из установленных приложений.
 */
function МимоVpn({ список, поменять }) {
  const [выбор, показатьВыбор] = useState(null); // null — закрыт, иначе найденные программы
  const [ищем, установитьПоиск] = useState(false);
  const [отбор, установитьОтбор] = useState("");

  const добавить = (программа) => {
    if (!программа || список.some((п) => п.путь === программа.путь)) return;
    поменять([...список, программа]);
  };

  const открытьВыбор = async () => {
    установитьПоиск(true);
    установитьОтбор("");
    try {
      показатьВыбор(await invoke("запущенные_программы"));
    } catch {
      показатьВыбор([]);
    } finally {
      установитьПоиск(false);
    }
  };

  const указатьФайл = async () => {
    try {
      добавить(await invoke("выбрать_программу"));
    } catch {
      /* человек закрыл окно выбора */
    }
  };

  const подходящие = (выбор ?? []).filter(
    (п) =>
      !список.some((с) => с.путь === п.путь) &&
      (п.имя + " " + п.путь).toLowerCase().includes(отбор.trim().toLowerCase()),
  );

  return (
    <section className="мимо">
      <div className="настройка-текст">
        <span className="настройка-имя">{телефон ? "Приложения мимо VPN" : "Программы мимо VPN"}</span>
        <span className="настройка-пояснение">
          Их трафик пойдёт напрямую, всё остальное — через VPN. Изменения применятся при следующем
          подключении
        </span>
      </div>

      {список.length > 0 && (
        <ul className="мимо-список">
          {список.map((п) => (
            <li key={п.путь} className="мимо-строка" title={п.путь}>
              <span className="мимо-имя">{п.имя}</span>
              <button
                className="мимо-убрать"
                onClick={() => поменять(список.filter((с) => с.путь !== п.путь))}
                aria-label={`Убрать ${п.имя}`}
              >
                ×
              </button>
            </li>
          ))}
        </ul>
      )}

      {выбор === null ? (
        <div className="мимо-кнопки">
          <button className="кнопка-шапки" onClick={открытьВыбор} disabled={ищем}>
            {ищем ? "Ищем…" : телефон ? "Добавить приложение" : "Добавить из запущенных"}
          </button>
          {!телефон && (
            <button className="кнопка-шапки" onClick={указатьФайл}>
              Указать файл…
            </button>
          )}
        </div>
      ) : (
        <div className="мимо-выбор">
          <input
            className="поле мелкое"
            placeholder="Найти по названию"
            value={отбор}
            onChange={(е) => установитьОтбор(е.target.value)}
          />
          <ul className="мимо-найдено">
            {подходящие.length === 0 && <li className="строка мелко">Ничего не найдено</li>}
            {подходящие.map((п) => (
              <li key={п.путь}>
                <button className="мимо-вариант" onClick={() => добавить(п)} title={п.путь}>
                  {п.имя}
                </button>
              </li>
            ))}
          </ul>
          <button className="кнопка второстепенная" onClick={() => показатьВыбор(null)}>
            Готово
          </button>
        </div>
      )}
    </section>
  );
}
