import { useEffect, useState } from "react";
import { invoke } from "@tauri-apps/api/core";
import { getVersion } from "@tauri-apps/api/app";

// Автозапуск, трей и свёрнутое окно — понятия компьютера. На телефоне
// их нет, поэтому там эти переключатели не показываем.
const телефон = navigator.userAgent.includes("Android");

/** Окошко настроек поверх главного экрана. */
export default function Настройки({ закрыть }) {
  const [свойства, установить] = useState(null);
  const [беда, установитьБеду] = useState("");
  const [версия, установитьВерсию] = useState("");

  useEffect(() => {
    getVersion().then(установитьВерсию).catch(() => {});
  }, []);

  useEffect(() => {
    (async () => {
      try {
        установить(await invoke("настройки"));
      } catch (е) {
        установитьБеду(String(е));
      }
    })();
  }, []);

  const поменять = async (ключ, значение) => {
    const новые = { ...свойства, [ключ]: значение };
    установить(новые);
    try {
      await invoke("сохранить_настройки", { новые });
    } catch (е) {
      установитьБеду(String(е));
    }
  };

  return (
    <div className="затемнение" onClick={закрыть}>
      <div className="окошко" onClick={(е) => е.stopPropagation()}>
        <div className="окошко-шапка">
          <span>Настройки</span>
          <button className="значок" onClick={закрыть}>
            Закрыть
          </button>
        </div>

        {телефон ? (
          <p className="строка">
            На телефоне настраивать нечего: VPN включается и выключается кнопкой, а в фоне работает сам
          </p>
        ) : !свойства ? (
          <p className="строка">Читаем настройки…</p>
        ) : (
          <>
            <Переключатель
              имя="Запускать вместе с Windows"
              пояснение="Приложение будет стартовать при входе в систему"
              включено={свойства.с_виндой}
              поменять={(з) => поменять("с_виндой", з)}
            />
            <Переключатель
              имя="Подключаться сразу при запуске"
              пояснение="Сразу поднимать туннель на последнем сервере"
              включено={свойства.сразу_подключаться}
              поменять={(з) => поменять("сразу_подключаться", з)}
            />
            <Переключатель
              имя="Запускаться свёрнутым"
              пояснение="Окно не будет открываться при старте системы"
              включено={свойства.свёрнутым}
              поменять={(з) => поменять("свёрнутым", з)}
            />
            <Переключатель
              имя="Закрывать в трей"
              пояснение="Крестик сворачивает, а не выключает туннель"
              включено={свойства.в_трей}
              поменять={(з) => поменять("в_трей", з)}
            />
          </>
        )}

        {беда && <p className="беда">{беда}</p>}
        {версия && <p className="версия-приложения">CryVPN {версия}</p>}
      </div>
    </div>
  );
}

function Переключатель({ имя, пояснение, включено, поменять }) {
  return (
    <label className="настройка">
      <span className="настройка-текст">
        <span className="настройка-имя">{имя}</span>
        <span className="настройка-пояснение">{пояснение}</span>
      </span>
      <input
        type="checkbox"
        className="галка"
        checked={!!включено}
        onChange={(е) => поменять(е.target.checked)}
      />
    </label>
  );
}
