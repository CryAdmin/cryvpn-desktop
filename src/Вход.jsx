import { useEffect, useRef, useState } from "react";
import { invoke } from "@tauri-apps/api/core";

// Два шага, как на сайте: почта, потом код из письма.
// Либо вход через Telegram: открываем бота, человек нажимает там «Войти»,
// а мы раз в две секунды спрашиваем кабинет, нажал ли.
const ШАГ_ПОЧТА = "почта";
const ШАГ_КОД = "код";
const ШАГ_ТЕЛЕГРАМ = "телеграм";
const ЖДАТЬ_ТЕЛЕГРАМ_МС = 5 * 60 * 1000;

export default function Вход({ вошли }) {
  const [шаг, установитьШаг] = useState(ШАГ_ПОЧТА);
  const [почта, установитьПочту] = useState("");
  const [код, установитьКод] = useState("");
  const [занят, установитьЗанятость] = useState(false);
  const [ошибка, установитьОшибку] = useState("");

  // Сколько секунд осталось до разрешённой повторной отправки. Сервер
  // чаще раза в минуту код не шлёт, а каждый новый код отменяет прежний —
  // поэтому кнопку повтора держим закрытой и объясняем, почему.
  const [пауза, установитьПаузу] = useState(0);
  useEffect(() => {
    if (пауза <= 0) return;
    const часы = setTimeout(() => установитьПаузу((с) => с - 1), 1000);
    return () => clearTimeout(часы);
  }, [пауза]);

  const выслатьКод = async (событие) => {
    событие?.preventDefault?.();
    установитьЗанятость(true);
    установитьОшибку("");
    try {
      const ответ = await invoke("выслать_код", { почта });
      if (ответ.ok) {
        установитьКод("");
        установитьПаузу(60);
        установитьШаг(ШАГ_КОД);
      } else установитьОшибку(ответ.сообщение);
    } catch (беда) {
      установитьОшибку(String(беда));
    } finally {
      установитьЗанятость(false);
    }
  };

  // Номер текущей попытки входа через Telegram. Сменился — старый опрос
  // должен замолчать: человек нажал «Отмена» или закрыл экран.
  const попытка = useRef(0);
  useEffect(() => () => { попытка.current += 1; }, []);

  const отменитьТелеграм = () => {
    попытка.current += 1;
    установитьШаг(ШАГ_ПОЧТА);
    установитьЗанятость(false);
  };

  const черезТелеграм = async () => {
    const моя = ++попытка.current;
    установитьЗанятость(true);
    установитьОшибку("");
    try {
      const начало = await invoke("телеграм_начать");
      if (моя !== попытка.current) return;
      if (!начало.ok) {
        установитьОшибку(начало.сообщение);
        return;
      }
      await invoke("открыть_ссылку", { адрес: начало.адрес });
      установитьШаг(ШАГ_ТЕЛЕГРАМ);

      const крайний = Date.now() + ЖДАТЬ_ТЕЛЕГРАМ_МС;
      while (Date.now() < крайний) {
        await new Promise((готово) => setTimeout(готово, 2000));
        if (моя !== попытка.current) return;
        const опрос = await invoke("телеграм_опрос", { токен: начало.токен });
        if (моя !== попытка.current) return;
        if (опрос.состояние === "вошли") {
          вошли(await invoke("профиль"));
          return;
        }
        if (опрос.состояние === "отказ") {
          установитьОшибку(опрос.сообщение);
          установитьШаг(ШАГ_ПОЧТА);
          return;
        }
      }
      установитьОшибку("Вход не подтвердили за пять минут. Начните заново");
      установитьШаг(ШАГ_ПОЧТА);
    } catch (беда) {
      if (моя === попытка.current) {
        установитьОшибку(String(беда));
        установитьШаг(ШАГ_ПОЧТА);
      }
    } finally {
      if (моя === попытка.current) установитьЗанятость(false);
    }
  };

  const войти = async (событие) => {
    событие.preventDefault();
    установитьЗанятость(true);
    установитьОшибку("");
    try {
      const ответ = await invoke("проверить_код", { почта, код });
      if (!ответ.ok) {
        установитьОшибку(ответ.сообщение);
        return;
      }
      вошли(await invoke("профиль"));
    } catch (беда) {
      установитьОшибку(String(беда));
    } finally {
      установитьЗанятость(false);
    }
  };

  return (
    <main className="экран по-центру">
      <h1 className="знак">CryVPN</h1>

      {шаг === ШАГ_ПОЧТА ? (
        <form className="поля" onSubmit={выслатьКод}>
          <p className="строка">Войдите той же почтой, что и на сайте</p>
          <input
            className="поле"
            type="email"
            inputMode="email"
            autoFocus
            placeholder="почта@example.com"
            value={почта}
            onChange={(e) => установитьПочту(e.target.value)}
            required
          />
          <button className="кнопка" disabled={занят}>
            {занят ? "Отправляем…" : "Получить код"}
          </button>
          <p className="или">или</p>
          <button type="button" className="кнопка телеграм" disabled={занят} onClick={черезТелеграм}>
            Войти через Telegram
          </button>
        </form>
      ) : шаг === ШАГ_ТЕЛЕГРАМ ? (
        <div className="поля">
          <p className="строка">
            Открылся Telegram. Нажмите там «Войти» — приложение войдёт само
          </p>
          <p className="строка мелко ожидание">Ждём подтверждения…</p>
          <button type="button" className="кнопка второстепенная" onClick={отменитьТелеграм}>
            Отмена
          </button>
        </div>
      ) : (
        <form className="поля" onSubmit={войти}>
          <p className="строка">Код отправлен на {почта}</p>
          <p className="строка мелко">
            Письмо может идти несколько минут. Подходит только код из последнего письма
          </p>
          <input
            className="поле код"
            inputMode="numeric"
            autoFocus
            placeholder="— — — — — —"
            value={код}
            onChange={(e) => установитьКод(e.target.value)}
            required
          />
          <button className="кнопка" disabled={занят}>
            {занят ? "Проверяем…" : "Войти"}
          </button>
          <button
            type="button"
            className="кнопка второстепенная"
            disabled={занят || пауза > 0}
            onClick={выслатьКод}
          >
            {пауза > 0 ? `Отправить код ещё раз через ${пауза} с` : "Отправить код ещё раз"}
          </button>
          <button
            type="button"
            className="кнопка второстепенная"
            onClick={() => {
              установитьШаг(ШАГ_ПОЧТА);
              установитьОшибку("");
            }}
          >
            Другая почта
          </button>
        </form>
      )}

      {ошибка && <p className="беда">{ошибка}</p>}
    </main>
  );
}
