#!/bin/sh
# Выполняется установщиком пакета (.deb и .rpm) после раскладки файлов.
#
# Ядру выдаётся одно право — управлять сетью: без него не создать
# туннельный адаптер и не прописать маршруты. Благодаря этому приложение
# поднимает VPN от имени самого человека и не просит пароль администратора.
# Не вышло выдать (нет setcap, раздел без поддержки) — не беда: приложение
# заметит это само и попросит пароль при подключении.
SC="$(command -v setcap || echo /usr/sbin/setcap)"
if [ -x "$SC" ] && [ -f /usr/lib/CryVPN/resources/xray ]; then
  "$SC" cap_net_admin,cap_net_raw+ep /usr/lib/CryVPN/resources/xray || true
fi
exit 0
