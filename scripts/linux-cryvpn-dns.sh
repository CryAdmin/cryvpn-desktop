#!/bin/sh
# Задаёт DNS для туннельного интерфейса CryVPN — и больше ничего.
#
# Запускается с правами root через pkexec: службе DNS системы
# (systemd-resolved) адрес для интерфейса может сообщить только
# администратор. Чтобы этим нельзя было воспользоваться не по делу,
# сценарий умеет ровно одно: интерфейс зашит, а в доводах принимаются
# только адреса IPv4, не больше двух. Запись живёт, пока поднят туннель:
# интерфейс исчезает — служба забывает адрес сама. Общие настройки DNS
# системы не меняются.
IF=CryVPN
[ "$#" -ge 1 ] && [ "$#" -le 2 ] || exit 2
for a in "$@"; do
  case "$a" in
    *[!0-9.]*|'') exit 2 ;;
  esac
  echo "$a" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}$' || exit 2
done
RC="$(command -v resolvectl || echo /usr/bin/resolvectl)"
[ -x "$RC" ] || exit 4
ip link show "$IF" >/dev/null 2>&1 || exit 5
"$RC" dns "$IF" "$@" || exit 1
# Все запросы — через туннель: иначе служба спрашивала бы и прежний DNS.
"$RC" domain "$IF" '~.' || exit 1
"$RC" default-route "$IF" yes || exit 1
exit 0
